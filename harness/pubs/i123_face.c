/* One script element: a host event message and its qemu token. */
typedef struct { int32_t msg; char tok[24]; } stroke_t;
static const char *char_token(char c, char *buf)
{
    static const struct { char c; const char *t; } MAP[] = {
        {' ',"spc"},{'.',"dot"},{'/',"slash"},{'-',"minus"},{'+',"shift-equal"},{'*',"shift-8"},
        {'@',"shift-2"},{'(',"shift-9"},{')',"shift-0"},{',',"comma"},{':',"shift-semicolon"},
        {';',"semicolon"},{'$',"shift-4"},{'\'',"apostrophe"},{'"',"shift-apostrophe"},
        {'^',"shift-6"},{'#',"shift-3"},{'<',"shift-comma"},{'>',"shift-dot"},{'=',"equal"},
        {'&',"shift-7"},{'\\',"backslash"},{'|',"shift-backslash"},{'%',"shift-5"},{'!',"shift-1"},
        {'?',"shift-slash"},{'_',"shift-minus"},
    };
    if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')) { buf[0] = c; buf[1] = 0; return buf; }
    if (c >= 'A' && c <= 'Z') { snprintf(buf, 24, "shift-%c", c - 'A' + 'a'); return buf; }
    for (size_t i = 0; i < sizeof MAP / sizeof MAP[0]; i++) if (MAP[i].c == c) return MAP[i].t;
    return 0;
}
static size_t parse_line(const char *line, const char *path, stroke_t *out, size_t n, size_t cap)
{
    for (const char *p = line; *p; p++) {
        if (n >= cap) die("script too long", path);
        stroke_t *s = &out[n];
        if (*p == '{') {
            const char *e = strchr(p, '}'); size_t k;
            if (!e) die("unterminated {", path);
            for (k = 0; k < NKEYS; k++)
                if (KEYS[k].brace[0] == '{' && (size_t)(e - p + 1) == strlen(KEYS[k].brace) &&
                    !strncmp(p, KEYS[k].brace, (size_t)(e - p + 1))) break;
            if (k == NKEYS) die("unknown key name", p);
            s->msg = KEYS[k].msg; snprintf(s->tok, sizeof s->tok, "%s", KEYS[k].qemu);
            p = e;
        } else if (*p == '~') {
            s->msg = (0x1c << 8) | 13; snprintf(s->tok, sizeof s->tok, "ret");
        } else {
            char b[24]; const char *t = char_token(*p, b);
            if (!t) { char d[2] = { *p, 0 }; die("no key for character", d); }
            s->msg = (uint8_t)*p; snprintf(s->tok, sizeof s->tok, "%s", t);
        }
        n++;
    }
    return n;
}
static size_t parse_keys(const char *path, stroke_t *out, size_t cap)
{
    FILE *f = fopen(path, "rb"); char line[1024]; size_t n = 0;
    if (!f) die("open", path);
    while (fgets(line, sizeof line, f)) {
        line[strcspn(line, "\r\n")] = 0;
        if (line[0] == '#') continue;
        n = parse_line(line, path, out, n, cap);
    }
    fclose(f);
    return n;
}
static void type_text(const char *s)
{
    for (; *s; s++) {
        if (*s == '~') ev(keyDown, (0x1c << 8) | 13);
        else ev(keyDown, (uint8_t)*s);
    }
}
