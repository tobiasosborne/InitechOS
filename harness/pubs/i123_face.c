/* ---- the menu resource walked ----------------------------------------- */
typedef struct { char path[160]; uint16_t idx[12]; int depth; int leaf; } mpath_t;
static mpath_t g_paths[512];
static int g_npaths;
static void walk(uint16_t level, const char *prefix, const uint16_t *idx, int depth)
{
    const i123_menu_level_t *lv = &i123_menu_levels[level];
    for (uint16_t i = 0; i < lv->count; i++) {
        const i123_menu_item_t *it = &i123_menu_items[lv->first + i];
        mpath_t *m = &g_paths[g_npaths++];
        if (g_npaths > 512 || depth >= 12) die("menu", "resource too large");
        snprintf(m->path, sizeof m->path, "%s%s%s", prefix, depth ? " " : "/", i123_menu_string(it->name));
        memcpy(m->idx, idx, sizeof(uint16_t) * (size_t)depth);
        m->idx[depth] = i; m->depth = depth + 1; m->leaf = it->child == 65535;
        if (!m->leaf) walk(it->child, m->path, m->idx, depth + 1);
    }
}
static void load_menu(void)
{ i123_menu_init(); g_npaths = 0; uint16_t z[12] = { 0 }; walk(0, "", z, 0); }

/* Each probe runs in a fork()ed child: every launch is a pristine image. */
static int child(int (*fn)(void *), void *arg)
{
    pid_t p = fork(); int st;
    if (p < 0) die("fork", "");
    if (p == 0) _exit(fn(arg) & 0xff);
    if (waitpid(p, &st, 0) < 0 || !WIFEXITED(st)) die("probe", "child died");
    return WEXITSTATUS(st);
}
/* 0 = the leaf acts, 1 = it answers "Command not implemented". */
static int probe_leaf(void *arg)
{
    const mpath_t *m = arg;
    launch();
    type_text("/");
    for (int d = 0; d < m->depth; d++) {
        for (int k = 0; k < m->idx[d]; k++) ev(keyDown, 0x4d << 8);
        ev(keyDown, (0x1c << 8) | 13);
    }
    return g_mode == M_NOTICE && g_notice && !strcmp(g_notice, "Command not implemented");
}
/* 0 = stored, 1 = the compiler refused (EDIT). */
static int probe_function(void *arg)
{
    const wkf_token_t *t = arg; char text[96]; size_t n;
    launch();
    n = (size_t)snprintf(text, sizeof text, "%s", t->name);
    if (t->arity) {
        text[n++] = '(';
        for (int a = 0; a < t->arity; a++) {
            const char *v = (t->rmask >> a) & 1 ? "A1..A2" : "1";
            n += (size_t)snprintf(text + n, sizeof text - n, "%s%s", a ? "," : "", v);
        }
        text[n++] = ')'; text[n] = 0;
    }
    ev(keyDown, 0x3f << 8); type_text("C3~");
    type_text(text); type_text("~");
    return !(g_mode == M_READY && i123_find(&g_sheet, 2, 2) && i123_find(&g_sheet, 2, 2)->kind == I123_K_FORMULA);
}
/* A snapshot of everything the key might change. */
typedef struct { char scr[SH][SW + 1]; int mode; uint16_t c, r; uint32_t ncells; uint32_t elen; } snap_t;
static void snap(snap_t *s)
{
    memcpy(s->scr, m_scr, sizeof m_scr); s->mode = g_mode;
    s->c = i123_cursor_col(&g_sheet); s->r = i123_cursor_row(&g_sheet); s->ncells = g_sheet.ncells; s->elen = g_elen;
}
/* Probe contexts: 0 READY (pointer on B2 of a small sheet), 1 MENU (the
 * main menu, second item highlighted), 2 LABEL entry in progress, 3 the
 * RANGE prompt of /Range Erase, 4 MANUAL recalculation with a formula left
 * stale (the CALC indicator lit). Returns 1 when the key acted. */
static int probe_key(void *arg)
{
    const int *a = arg; snap_t before, after;
    launch();
    type_text("Alpha"); ev(keyDown, 0x50 << 8); type_text("10"); ev(keyDown, 0x4d << 8);
    type_text("20~");
    if (a[1] == 1) { type_text("/"); ev(keyDown, 0x4d << 8); }
    if (a[1] == 2) type_text("Abc");
    if (a[1] == 3) type_text("/re");
    if (a[1] == 4) { type_text("/wgrm"); ev(keyDown, 0x50 << 8); type_text("@sum(a2..b2)~"); ev(keyDown, 0x48 << 8); type_text("30~"); }
    snap(&before);
    ev(keyDown, KEYS[a[0]].msg);
    snap(&after);
    return memcmp(&before, &after, sizeof before) != 0;
}

static void cmd_inventory(void)
{
    load_menu();
    for (int i = 0; i < g_npaths; i++) printf("%s|menu\n", g_paths[i].path);
    static const wkf_token_t T[] = WKF_TOKENS_INIT;
    int nf = 0;
    for (size_t i = WKF_FIRST_FN; i <= WKF_LAST_FN; i++) {
        if (!T[i].name || T[i].name[0] != '@') continue;
        if (child(probe_function, (void *)&T[i]) == 0) { printf("%s|function\n", T[i].name); nf++; }
    }
    if (nf < 10) die("functions", "fewer than ten @functions accepted -- the probe is broken");
    int nk = 0;
    for (size_t k = 0; k < NKEYS; k++) {
        int acted = 0;
        for (int ctx = 0; ctx < 5 && !acted; ctx++) { int a[2] = { (int)k, ctx }; acted = child(probe_key, a); }
        if (acted) { printf("%s|key\n", KEYS[k].name); nk++; }
    }
    if (nk < 5) die("keys", "fewer than five keys act -- the probe is broken");
}
static void cmd_refusals(void)
{
    int nr = 0;
    load_menu();
    for (int i = 0; i < g_npaths; i++)
        if (g_paths[i].leaf && child(probe_leaf, &g_paths[i]) == 1) { printf("%s|refused\n", g_paths[i].path); nr++; }
    if (!nr) die("refusals", "no leaf refuses -- the probe is broken or the ledger is stale");
}

/* AN-08: the boxed menu tree of one top-level command, as TeX for the
 * I123Tree environment of pubs/class/initech-lotus.sty. */
static void tex_word(const char *s)
{
    for (; *s; s++) {
        if (*s == '&' || *s == '%' || *s == '$' || *s == '#' || *s == '_' || *s == '{' || *s == '}') printf("\\%c", *s);
        else if (*s == '\\') printf("\\textbackslash{}");
        else if (*s == '^') printf("\\textasciicircum{}");
        else if (*s == '~') printf("\\textasciitilde{}");
        else putchar(*s);
    }
}
static int g_box;
static void tree_box(uint16_t level, int parent_box, int parent_item, int bold)
{
    const i123_menu_level_t *lv = &i123_menu_levels[level];
    int me = g_box++;
    if (parent_box < 0) printf("\\TreeBox{b%d}{}{", me);
    else printf("\\TreeBox{b%d}{b%dw%d}{", me, parent_box, parent_item);
    for (uint16_t i = 0; i < lv->count; i++) {
        printf("%s{", (int)i == bold ? "\\TreeWB" : "\\TreeW");
        tex_word(i123_menu_string(i123_menu_items[lv->first + i].name));
        printf("}");
    }
    printf("}\n");
}
/* depth first under one item: every level that item opens */
static void tree_under(uint16_t level, int box)
{
    const i123_menu_level_t *lv = &i123_menu_levels[level];
    for (uint16_t i = 0; i < lv->count; i++) {
        const i123_menu_item_t *it = &i123_menu_items[lv->first + i];
        if (it->child == 65535) continue;
        int child_box = g_box;
        tree_box(it->child, box, i, -1);
        tree_under(it->child, child_box);
    }
}
static void cmd_tree(const char *top)
{
    i123_menu_init();
    const i123_menu_level_t *lv = &i123_menu_levels[0];
    for (uint16_t i = 0; i < lv->count; i++) {
        const i123_menu_item_t *it = &i123_menu_items[lv->first + i];
        if (strcmp(i123_menu_string(it->name), top)) continue;
        printf("%% generated by harness/pubs/i123_face.c tree %s from the shipped menu resource\n", top);
        printf("\\begin{I123Tree}\n");
        g_box = 0;
        tree_box(0, -1, 0, i);
        if (it->child != 65535) { int c = g_box; tree_box(it->child, 0, i, -1); tree_under(it->child, c); }
        printf("\\end{I123Tree}\n");
        return;
    }
    die("tree", top);
}

static void cmd_run(const char *path)
{
    static stroke_t s[8192];
    size_t n = parse_keys(path, s, 8192);
    launch();
    for (size_t i = 0; i < n && !m_exited; i++) ev(keyDown, s[i].msg);
    print_screen();
}
static void cmd_tokens(const char *path)
{
    static stroke_t s[8192];
    size_t n = parse_keys(path, s, 8192);
    for (size_t i = 0; i < n; i++) printf("%sk%s", i ? "," : "", s[i].tok);
    printf("\n");
}
static void trim_cell(uint16_t c, uint16_t r, char *out)
{
    char text[256]; uint32_t spill; size_t a = 0, b;
    i123_cell_text(&g_sheet, i123_find(&g_sheet, c, r), i123_colwidth(&g_sheet, c), text, &spill);
    b = strlen(text);
    while (a < b && text[a] == ' ') a++;
    while (b > a && text[b - 1] == ' ') b--;
    memcpy(out, text + a, b - a); out[b - a] = 0;
}
static void cmd_replay(const char *path)
{
    FILE *f = fopen(path, "rb"); char line[512];
    if (!f) die("open", path);
    launch();
    /* the scratch column IV is 40 characters wide (Set-Width) */
    ev(keyDown, 0x3f << 8); type_text("IV8192~"); type_text("/wcs40~");
    if (g_mode != M_READY) die("replay", "the scratch column could not be widened");
    while (fgets(line, sizeof line, f)) {
        line[strcspn(line, "\r\n")] = 0;
        if (!line[0] || line[0] == '#') continue;
        if (line[0] == '=' && line[1] == ' ') {
            char shown[256];
            ev(keyDown, 0x3f << 8); type_text("IV8192~");
            type_text(line + 2); type_text("~");
            if (g_mode != M_READY) die("entry refused", line);
            trim_cell(255, 8191, shown);
            printf("%s = %s\n", line + 2, shown);
            continue;
        }
        if (!strncmp(line, "do ", 3)) {
            static stroke_t k[1024];
            size_t nk = parse_line(line + 3, path, k, 0, 1024);
            for (size_t i = 0; i < nk; i++) ev(keyDown, k[i].msg);
            if (g_mode != M_READY) die("keys did not end in READY", line);
            continue;
        }
        if (!strncmp(line, "show ", 5)) {
            char content[I123_FTEXT_MAX], shown[256]; i123_rect_t r;
            if (i123_range_parse(&g_sheet, line + 5, &r) || r.c0 != r.c1 || r.r0 != r.r1) die("bad show", line);
            i123_cell_content(&g_sheet, i123_find(&g_sheet, r.c0, r.r0), content, sizeof content);
            trim_cell(r.c0, r.r0, shown);
            printf("%s: %s = %s\n", line + 5, content, shown);
            continue;
        }
        char *sp = strchr(line, ' ');
        if (!sp) die("bad example line", line);
        *sp = 0;
        ev(keyDown, 0x3f << 8); type_text(line); type_text("~");
        type_text(sp + 1); type_text("~");
        if (g_mode != M_READY) die("entry refused", sp + 1);
        printf("%s: %s\n", line, sp + 1);
    }
    fclose(f);
}

int main(int argc, char **argv)
{
    if (argc >= 2 && !strcmp(argv[1], "inventory")) cmd_inventory();
    else if (argc >= 2 && !strcmp(argv[1], "refusals")) cmd_refusals();
    else if (argc == 3 && !strcmp(argv[1], "tree")) cmd_tree(argv[2]);
    else if (argc == 3 && !strcmp(argv[1], "tokens")) cmd_tokens(argv[2]);
    else if ((argc == 3 || argc == 4) && !strcmp(argv[1], "run")) { if (argc == 4) m_dir = argv[3]; cmd_run(argv[2]); }
    else if (argc == 3 && !strcmp(argv[1], "replay")) cmd_replay(argv[2]);
    else die("usage", "inventory | refusals | tree TOP | tokens FILE | run FILE [DIR] | replay FILE");
    return ferror(stdout) ? 1 : 0;
}
