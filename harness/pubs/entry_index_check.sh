#!/bin/sh
# Ref: F4 review of 556e9d05; CLAUDE.md Rules 1/6/11.
# Exercise the real pubs.mk discovery/rule in an isolated source tree.
set -eu
work=$(mktemp -d "${TMPDIR:-/tmp}/initech-entry-index-XXXXXX")
trap 'rm -rf "$work"' EXIT
trap 'exit 1' HUP INT TERM
mkdir -p "$work/pubs/manuals/fixture/entries/fn"
# Tracked keepers preserve empty groups across clean checkouts as well as rm.
for group in pubs/manuals/*/entries/*/; do
    [ -f "$group/.gitkeep" ] || {
        printf '!!! entry-index RED: group lacks a tracked directory keeper: %s\n' "$group" >&2
        exit 1
    }
done
: > "$work/pubs/manuals/fixture/entries/fn/.gitkeep"
cp -f pubs/pubs.mk pubs/turbo.mk pubs/entry-index.sh "$work/pubs/"
printf 'BUILD := build\ninclude pubs/pubs.mk\n' > "$work/Makefile"
cd "$work"
dir=pubs/manuals/fixture/entries/fn
idx=build/pubs/gen/entries-fixture-fn.tex
make=${MAKE:-make}
rebuild() {
    "$make" --no-print-directory "$idx" > make.log 2>&1 || {
        cat make.log; exit 1;
    }
}
header='% Generated by pubs/entry-index.sh from entries/fn -- do not edit.'
for key in z do-while do a_0 A; do printf 'entry\n' > "$dir/$key.tex"; done
printf 'not an entry\n' > "$dir/README.txt"
cat > expected <<'EOF'
% Generated by pubs/entry-index.sh from entries/fn -- do not edit.
\input{entries/fn/A}%
\input{entries/fn/a_0}%
\input{entries/fn/do}%
\input{entries/fn/do-while}%
\input{entries/fn/z}%
EOF
rebuild
cmp expected "$idx"
# Reverse creation order; compare actual shell output in another locale too.
rm -f "$dir"/*.tex
for key in A a_0 do do-while z; do printf 'entry\n' > "$dir/$key.tex"; done
LC_ALL=POSIX sh pubs/entry-index.sh "$dir" > direct
cmp expected direct
sleep 1
printf 'entry\n' > "$dir/b.tex"
rebuild
grep -qFx '\input{entries/fn/b}%' "$idx"
sleep 1
rm -f "$dir"/*.tex
rebuild
printf '%s\n' "$header" > empty
cmp empty "$idx" || {
    printf '!!! entry-index RED: removing the last entry left a stale index\n' >&2
    exit 1
}
# The generator must fail before emitting any TeX for an unsafe key.
printf 'entry\n' > "$dir/bad%name.tex"
rc=0
sh pubs/entry-index.sh "$dir" > unsafe.out 2> unsafe.log || rc=$?
[ "$rc" -eq 1 ] && [ ! -s unsafe.out ] && grep -qF 'invalid entry key' unsafe.log || {
    cat unsafe.log
    printf '!!! entry-index RED: unsafe key was not rejected\n' >&2
    exit 1
}
printf '>>> test-pubs-entry-index: green (order, add/remove/empty group, unsafe key)\n'
