/* Generated tables of the InitechBase manuals (bead initech-ipu5.8;
 * PUB-REF-0001 AN-04 Limitations, CP-11 coercion appendix).  Nothing in
 * these tables is typed into a book: each value is read from the shipped
 * source or the locked spec data when the book is built.
 *
 *   samir_tables limits
 *       the Item / Limitations table of Using InitechBase Chapter 5 and the
 *       specification table of Chapter 1: the capacity constants of the
 *       SHIPPED engine -- spec/samir/dbf_format.h (fields per database),
 *       samir/workarea.h (work areas, index files per database), and the
 *       defines of cmd/flow.c, cmd/proc.c, cmd/report.c and samir_main.c,
 *       which are included whole for that (the single-TU pattern of
 *       int21_inventory.c); the rest of the engine is linked.
 *   samir_tables coercion <xbase_coercion.json>
 *       the operator and assignment tables of Appendix E, row for row from
 *       spec/samir/xbase_coercion.json (one row object per line, as the
 *       locked file is written; anything else is RED).  The rule of a row is
 *       printed through \CoercionRule{R_name}, whose text the book defines
 *       (an undefined rule is a TeX error, so no row loses its note).
 * Output: LaTeX on stdout.  Host C (Law 3). */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "../../os/samir/cmd/flow.c"
#include "../../os/samir/cmd/proc.c"
#include "../../os/samir/cmd/report.c"
#include "../../os/samir/samir_main.c"
#include "dbf_format.h"

static void row(const char *item, long v, const char *unit)
{ printf("%s & %ld%s%s \\\\\n", item, v, *unit ? " " : "", unit); }

static void limits(void)
{
    printf("%% Generated by harness/pubs/samir_tables.c limits -- do not edit.\n");
    row("Fields in a database", DBF_MAX_FIELDS, "");
    row("Open databases (work areas)", WA_NAREAS, "");
    row("Index files open with one database", NDX_PER_AREA, "");
    row("Memory variables", FLOW_MAX_MEMVARS, "");
    row("Characters in a memory variable name", FLOW_MAX_NAME - 1, "");
    row("Characters in a command line", FLOW_MAX_LINELEN, "");
    row("Lines in a program file", FLOW_MAX_LINES, "");
    row("Size of a program file", (long)REPL_PRG_CAP - 1, "bytes");
    row("Nested DO levels", FLOW_MAX_SCOPE, "");
    row("Arguments of DO ... WITH", P_MAX_ARGS, "");
    row("Columns in a report form", RP_COLS, "");
}

/* "key":"value" of one JSON row line, or NULL. */
static int field(const char *line, const char *key, char *out, size_t cap)
{
    char pat[64];
    snprintf(pat, sizeof pat, "\"%s\":", key);
    const char *p = strstr(line, pat);
    if (!p) return 0;
    p += strlen(pat);
    while (*p == ' ') p++;
    if (*p != '"') { fprintf(stderr, "!!! samir_tables: %s is not a string: %s", key, line); exit(1); }
    p++;
    size_t n = 0;
    while (*p && *p != '"') { if (n + 1 >= cap) exit(1); out[n++] = *p++; }
    if (*p != '"') { fprintf(stderr, "!!! samir_tables: unterminated %s\n", key); exit(1); }
    out[n] = 0;
    return 1;
}
static const char *typename(const char *t)
{
    if (!strcmp(t, "C")) return "Character";
    if (!strcmp(t, "N")) return "Numeric";
    if (!strcmp(t, "D")) return "Date";
    if (!strcmp(t, "L")) return "Logical";
    if (!strcmp(t, "M")) return "Memo";
    fprintf(stderr, "!!! samir_tables: unknown type %s\n", t); exit(1);
}
static void texop(const char *op)
{
    for (; *op; op++) {
        if (*op == '$' || *op == '#' || *op == '&' || *op == '%' || *op == '_') printf("\\%c", *op);
        else if (*op == '^') printf("\\textasciicircum{}");
        else if (*op == '<' || *op == '>') printf("%c", *op);
        else putchar(*op);
    }
}
static void coercion(const char *path)
{
    FILE *f = fopen(path, "rb");
    char line[1024], a[64], b[64], c[64], r[64], e[128], rule[64], msgs[8][2][96];
    int section = 0, rows = 0, nmsg = 0;
    if (!f) { fprintf(stderr, "!!! samir_tables: %s\n", path); exit(1); }
    printf("%% Generated by harness/pubs/samir_tables.c coercion from %s -- do not edit.\n", "spec/samir/xbase_coercion.json");
    while (fgets(line, sizeof line, f)) {
        if (strstr(line, "\"error_messages\"")) section = 3;
        else if (strstr(line, "\"operator_coercion\"")) {
            section = 1;
            printf("\\begin{CoercionTable}{Operator}\n");
        } else if (strstr(line, "\"assignment_coercion\"")) {
            if (section == 1) printf("\\end{CoercionTable}\n");
            section = 2;
            printf("\\begin{AssignmentTable}\n");
        } else if (section == 3) {
            /* "key": "message text", -- one per line */
            char *k1 = strchr(line, '"'), *k2, *v1, *v2;
            if (strchr(line, '}')) { section = 0; continue; }
            if (!k1 || !(k2 = strchr(k1 + 1, '"')) || !(v1 = strchr(k2 + 1, '"')) ||
                !(v2 = strchr(v1 + 1, '"')) || nmsg == 8) continue;
            *k2 = *v2 = 0;
            snprintf(msgs[nmsg][0], sizeof msgs[0][0], "%s", k1 + 1);
            snprintf(msgs[nmsg][1], sizeof msgs[0][1], "%s", v1 + 1);
            nmsg++;
        } else if ((section == 1 || section == 2) && strchr(line, '{')) {
            e[0] = rule[0] = 0;
            field(line, "rule", rule, sizeof rule);
            if (field(line, "error", e, sizeof e)) {
                int k, hit = -1;
                for (k = 0; k < nmsg; k++) if (!strcmp(msgs[k][0], e)) hit = k;
                if (hit < 0) { fprintf(stderr, "!!! samir_tables: error %s has no message\n", e); exit(1); }
                snprintf(e, sizeof e, "%s", msgs[hit][1]);
            }
            if (section == 1) {
                if (!field(line, "lhs", a, sizeof a) || !field(line, "op", b, sizeof b) ||
                    !field(line, "rhs", c, sizeof c) || !field(line, "result", r, sizeof r)) {
                    fprintf(stderr, "!!! samir_tables: bad operator row: %s", line); exit(1); }
                printf("\\texttt{"); texop(b); printf("} & %s & %s & ", typename(a), typename(c));
            } else {
                if (!field(line, "target", a, sizeof a) || !field(line, "expr", c, sizeof c) ||
                    !field(line, "result", r, sizeof r)) {
                    fprintf(stderr, "!!! samir_tables: bad assignment row: %s", line); exit(1); }
                printf("%s & %s & ", typename(a), typename(c));
            }
            if (!strcmp(r, "error")) printf("\\texttt{%s}", e);
            else if (!strcmp(r, "ok")) printf("Stored");
            else printf("%s", typename(r));
            printf(" & %s%s%s \\\\\n", rule[0] ? "\\CoercionRule{" : "", rule, rule[0] ? "}" : "");
            rows++;
        } else if ((section == 1 || section == 2) && strchr(line, ']')) {
            if (section == 2) { printf("\\end{AssignmentTable}\n"); section = 0; }
        }
    }
    fclose(f);
    if (rows < 20) { fprintf(stderr, "!!! samir_tables: only %d coercion rows\n", rows); exit(1); }
}

int main(int argc, char **argv)
{
    if (argc == 2 && !strcmp(argv[1], "limits")) limits();
    else if (argc == 3 && !strcmp(argv[1], "coercion")) coercion(argv[2]);
    else { fprintf(stderr, "usage: samir_tables limits | coercion <json>\n"); return 2; }
    return ferror(stdout) ? 1 : 0;
}
