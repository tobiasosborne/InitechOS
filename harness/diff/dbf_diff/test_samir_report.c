struct pal_host_cfg { uint8_t date_yy, date_mm, date_dd; uint32_t heap_size; };
samir_pal_t *pal_host_make(struct pal_host_cfg cfg);
void         pal_host_free(samir_pal_t *p);
extern int samir_repl(samir_pal_t *pal, xb_interp *ip);

#define CAP_BUF (1u << 20)
#define MAXL 128
typedef struct {
    samir_pal_t pal;          /* first: handed to the engine */
    samir_pal_t *in;
    char *buf; uint32_t len;
    const char *lines[MAXL]; int n, at;
} cap_pal;
static cap_pal C;

static pal_fd  c_open (samir_pal_t *p, const char *n, int m) { (void)p; return C.in->open(C.in, n, m); }
static int     c_close(samir_pal_t *p, pal_fd f) { (void)p; return C.in->close(C.in, f); }
static int32_t c_read (samir_pal_t *p, pal_fd f, void *b, uint32_t n) { (void)p; return C.in->read(C.in, f, b, n); }
static int32_t c_write(samir_pal_t *p, pal_fd f, const void *b, uint32_t n) { (void)p; return C.in->write(C.in, f, b, n); }
static int32_t c_seek (samir_pal_t *p, pal_fd f, int32_t o, int w) { (void)p; return C.in->seek(C.in, f, o, w); }
static int     c_rm   (samir_pal_t *p, const char *n) { (void)p; return C.in->remove(C.in, n); }
static int     c_mv   (samir_pal_t *p, const char *a, const char *b) { (void)p; return C.in->rename(C.in, a, b); }
static void    c_out  (samir_pal_t *p, const char *s, uint32_t n)
{
    (void)p;
    while (n-- && C.len < CAP_BUF - 1u) C.buf[C.len++] = *s++;
    C.buf[C.len] = 0;
}
static int32_t c_line (samir_pal_t *p, char *b, uint32_t cap)
{
    size_t k;
    (void)p;
    if (C.at >= C.n) return -1;
    k = strlen(C.lines[C.at]);
    if (k >= cap) k = cap - 1u;
    memcpy(b, C.lines[C.at++], k); b[k] = 0;
    return (int32_t)k;
}
static int32_t c_char (samir_pal_t *p) { (void)p; return C.in->conin_char(C.in); }
static void    c_xy   (samir_pal_t *p, uint8_t r, uint8_t c) { (void)p; C.in->gotoxy(C.in, r, c); }
static void    c_attr (samir_pal_t *p, uint8_t a) { (void)p; C.in->set_attr(C.in, a); }
static void    c_today(samir_pal_t *p, uint8_t *y, uint8_t *m, uint8_t *d) { (void)p; C.in->today(C.in, y, m, d); }
static void   *c_alloc(samir_pal_t *p, uint32_t n) { (void)p; return C.in->alloc(C.in, n); }
static void    c_reset(samir_pal_t *p, void *m) { (void)p; C.in->reset(C.in, m); }
static void   *c_acq  (samir_pal_t *p, uint32_t n) { (void)p; return C.in->acquire(C.in, n); }
static void    c_rel  (samir_pal_t *p, void *m) { (void)p; C.in->release(C.in, m); }

static const char *g_corpus;
static char g_root[1024];

static long slurp(const char *path, char **out)
{
    FILE *f = fopen(path, "rb");
    long n;
    *out = NULL;
    if (!f) return -1;
    fseek(f, 0, SEEK_END); n = ftell(f); fseek(f, 0, SEEK_SET);
    *out = malloc((size_t)n + 1u);
    if (fread(*out, 1, (size_t)n, f) != (size_t)n) n = -1;
    fclose(f);
    if (n >= 0) (*out)[n] = 0;
    return n;
}

/* The command lists below are the minted PRGs verbatim (USE ... INDEX TRIPS
 * with the default .NDX, no added GO TOP, no trailing SET reset): SAMIR now
 * defaults the index extension (initech-vfys), positions USE ... INDEX on the
 * first record in index order (initech-k7lc) and gives every interpreter
 * fresh SET state (initech-x5cc); mint 005, mint-results-005.md. */

/* Copy a corpus mint/work input into the session dir (the REPL opens RW). */
static void stage(const char *name)
{
    char src[1200], *b;
    long n = (snprintf(src, sizeof src, "%s/mint/work/%s", g_corpus, name), slurp(src, &b));
    FILE *f;
    CHECK(n > 0, "mint 004 input present in the corpus");
    if (n <= 0) { fprintf(stderr, "missing input %s\n", src); return; }
    f = fopen(name, "wb");
    CHECK(f && fwrite(b, 1, (size_t)n, f) == (size_t)n, "input staged byte-identically");
    if (f) fclose(f);
    free(b);
}

static void session(samir_pal_t *host, const char *dir, const char *const *in,
                    const char *const *cmd, int ncmd)
{
    char path[1200];
    xb_interp *ip;
    snprintf(path, sizeof path, "%s/%s", g_root, dir);
    mkdir(path, 0777);
    CHECK(chdir(path) == 0, "session directory entered");
    for (; *in; in++) stage(*in);
    C.len = 0; C.buf[0] = 0; C.n = 0; C.at = 0;
    for (; ncmd-- > 0 && C.n < MAXL - 1; cmd++) C.lines[C.n++] = *cmd;
    C.lines[C.n++] = "QUIT";
    ip = xb_interp_make(&C.pal);
    CHECK(ip != NULL, "interpreter constructed");
    if (!ip) return;
    CHECK(samir_repl(&C.pal, ip) == 0, "REPL returns cleanly");
    if (getenv("REPORT_TRACE")) fprintf(stderr, "== %s transcript ==\n%s\n", dir, C.buf);
    xb_interp_free(ip);
    (void)host;
}

/* No REPL error line ("<n>  <message>") may appear in a golden session. */
static void no_errors(const char *dir)
{
    const char *p = C.buf;
    int bad = 0;
    for (; *p; p++) {
        if ((p == C.buf || p[-1] == '\n' || (p - C.buf >= 2 && p[-1] == ' ' && p[-2] == '.' && (p - C.buf == 2 || p[-3] == '\n'))) && *p >= '0' && *p <= '9') {
            const char *q = p;
            while (*q >= '0' && *q <= '9') q++;
            if (q[0] == ' ' && q[1] == ' ') { bad = 1; fprintf(stderr, "%s: REPL error: %.60s\n", dir, p); }
        }
    }
    CHECK(!bad, "golden session ran without a REPL error");
}

/* The SAMIR file must equal the real one; the console carries it minus FF. */
static void diff(const char *out)
{
    char rp[1200], *got, *want, *con;
    long ng, nw, i, line = 1, k = 0;
    snprintf(rp, sizeof rp, "%s/mint/work/%s", g_corpus, out);
    nw = slurp(rp, &want);
    ng = slurp(out, &got);
    CHECK(nw > 0, "real dBASE golden present");
    CHECK(ng >= 0, "SAMIR wrote the TO FILE output");
    if (nw > 0 && ng >= 0) {
        int same = ng == nw && !memcmp(got, want, (size_t)nw);
        if (!same) {
            for (i = 0; i < ng && i < nw && got[i] == want[i]; i++) if (want[i] == '\n') line++;
            fprintf(stderr, "REPORT %s: differs from real dBASE at byte %ld (line %ld)\n", out, i, line);
            while (i > 0 && want[i - 1] != '\n') i--;
            fprintf(stderr, "  real : %.90s\n  samir: %.90s\n", want + i, i < ng ? got + i : "<eof>");
        }
        printf("  %-10s %s\n", out, same ? "byte-identical to real dBASE III PLUS 1.1" : "DIFFERS");
        CHECK(same, "REPORT FORM TO FILE byte-identical to real dBASE III PLUS 1.1");
        con = malloc((size_t)nw + 1u);
        for (i = 0; i < nw - 1; i++) if (want[i] != '\f') con[k++] = want[i];
        con[k] = 0;
        if (want[nw - 1] != 0x1a || strstr(C.buf, con) == NULL)
            fprintf(stderr, "REPORT %s: console differs from real screen stream\n", out);
        CHECK(want[nw - 1] == 0x1a && strstr(C.buf, con) != NULL,
              "console stream carries the same report without FF (real screen R4S*)");
        free(con);
    }
    free(got); free(want);
}

static void expect(samir_pal_t *host, const char *const *in, const char *cmd, const char *want, const char *why)
{
    const char *c[2];
    c[0] = "USE TRAVEL INDEX TRIPS"; c[1] = cmd;
    session(host, "refuse", in, c, 2);
    if (!strstr(C.buf, want)) fprintf(stderr, "TRANSCRIPT:\n%s\n", C.buf);
    CHECK(strstr(C.buf, want) != NULL, why);
}

#define N(a) ((int)(sizeof(a) / sizeof((a)[0])))
static char g_cmd[256][96];

int main(int argc, char **argv)
{
    scratch_lock("build/.lock-samir-report");
    struct pal_host_cfg cfg = { 86, 7, 24, 16u << 20 };   /* DATE 07/24/1986 as minted */
    samir_pal_t *host = pal_host_make(cfg);
    int i, n;
    static const char *const base[] = { "AVAL_FLT.DBF", "AVAL_FLT.NDX", "FLT_NO.NDX", "FLT_INFO.FRM",
        "TRAVEL.DBF", "TRAVEL.DBT", "TRIPS.NDX", "TRAVELER.FRM", "TRIP.FRM", "R4TRIP.DBF",
        "R4TRIP2.DBF", "R4FLTB.DBF", "UNIVERS.FRM", 0 };
    g_corpus = argc > 1 ? argv[1] : "../dbase3-decomp";
    if (!host || !getcwd(g_root, sizeof g_root - 32)) return 2;
    strcat(g_root, "/build/samir-report");
    mkdir(g_root, 0777);
    C.in = host; C.buf = malloc(CAP_BUF);
    C.pal.open = c_open; C.pal.close = c_close; C.pal.read = c_read; C.pal.write = c_write;
    C.pal.seek = c_seek; C.pal.remove = c_rm; C.pal.rename = c_mv; C.pal.conout = c_out;
    C.pal.conin_line = c_line; C.pal.conin_char = c_char; C.pal.gotoxy = c_xy;
    C.pal.set_attr = c_attr; C.pal.today = c_today; C.pal.alloc = c_alloc; C.pal.reset = c_reset;
    C.pal.acquire = c_acq; C.pal.release = c_rel;

    {   /* R4G.PRG: the clean session goldens (no SET ALTERNATE). */
        static const char *const cmd[] = {
            "USE AVAL_FLT INDEX AVAL_FLT, FLT_NO", "REPORT FORM FLT_INFO TO FILE G1FLT",
            "USE TRAVEL INDEX TRIPS", "REPORT FORM TRAVELER TO FILE G2TRV",
            "REPORT FORM TRAVELER PLAIN TO FILE G3TRVP", "REPORT FORM TRAVELER SUMMARY TO FILE G4TRVS",
            "REPORT FORM TRAVELER HEADING \"Mint session 004\" NOEJECT TO FILE G5TRVH",
            "GO TOP", "REPORT FORM TRAVELER NEXT 7 FOR PAID TO FILE G6TRVN",
            "USE TRAVEL", "REPORT FORM TRAVELER WHILE TRAVELCODE <> \"ZZZZ\" TO FILE G7TRVU",
            "USE R4TRIP", "REPORT FORM TRIP TO FILE G8TP", "REPORT FORM TRIP SUMMARY TO FILE G9TS",
            "REPORT FORM TRIP PLAIN TO FILE GATL",
            "USE R4FLTB", "REPORT FORM FLT_INFO TO FILE GBFB",
            "REPORT FORM FLT_INFO HEADING \"a fairly long run-time heading\" TO FILE GCFH",
            "REPORT FORM FLT_INFO PLAIN TO FILE GDFP" };
        static const char *const out[] = { "G1FLT.TXT", "G2TRV.TXT", "G3TRVP.TXT", "G4TRVS.TXT",
            "G5TRVH.TXT", "G6TRVN.TXT", "G7TRVU.TXT", "G8TP.TXT", "G9TS.TXT", "GATL.TXT",
            "GBFB.TXT", "GCFH.TXT", "GDFP.TXT" };
        printf("session R4G (shipped FLT_INFO / TRAVELER / TRIP forms):\n");
        session(host, "r4g", base, cmd, N(cmd)); no_errors("r4g");
        for (i = 0; i < N(out); i++) diff(out[i]);
        /* Same R4G session and independent real-software goldens; change
         * grammar words only, preserving the pagination context. */
        const char *abbr[N(cmd)];
        for (i = 0; i < N(cmd); i++) abbr[i] = cmd[i];
        abbr[2] = "USE TRAVEL INDE TRIPS";
        abbr[4] = "REPO FORM TRAVELER PLAI TO FILE G3TRVP";
        abbr[5] = "REPO FORM TRAVELER SUMM TO FILE G4TRVS";
        abbr[6] = "REPO FORM TRAVELER HEAD \"Mint session 004\" NOEJ TO FILE G5TRVH";
        session(host, "r4g-abbrev", base, abbr, N(abbr)); no_errors("abbreviated report");
        for (i = 0; i < N(out); i++) diff(out[i]);
    }
    {   /* R4D.PRG: wrap / ';' / overflow / long HEADING / scope probes. */
        static const char *const cmd[] = {
            "USE R4TRIP2", "REPORT FORM TRIP TO FILE R4DT", "USE TRAVEL INDEX TRIPS",
            "REPORT FORM TRAVELER NEXT 4 HEADING \"This is a very long heading that runs right across the page\" TO FILE R4DH",
            "REPORT FORM TRAVELER NEXT 4 HEADING \"\" TO FILE R4DE",
            "REPORT FORM TRAVELER RECORD 5 PLAIN SUMMARY TO FILE R4DS",
            "REPORT FORM TRAVELER WHILE TRAVELCODE = \"AO\" TO FILE R4DW",
            "REPORT FORM TRAVELER FOR .F. TO FILE R4DF" };
        static const char *const out[] = { "R4DT.TXT", "R4DH.TXT", "R4DE.TXT", "R4DS.TXT", "R4DW.TXT", "R4DF.TXT" };
        printf("session R4D (content probes):\n");
        session(host, "r4d", base, cmd, N(cmd)); no_errors("r4d");
        for (i = 0; i < N(out); i++) diff(out[i]);
    }
    {   /* R4H.PRG: empty selection with totals, ';' in HEADING, SET CENTURY. */
        static const char *const cmd[] = {
            "USE R4TRIP", "REPORT FORM TRIP FOR .F. TO FILE R4HT", "USE TRAVEL INDEX TRIPS", "GO TOP",
            "REPORT FORM TRAVELER NEXT 2 HEADING \"semi;colon\" TO FILE R4HS",
            "SET CENTURY ON", "USE R4FLTB", "REPORT FORM FLT_INFO NEXT 2 TO FILE R4HC" };
        printf("session R4H (empty totals, heading ';', century):\n");
        session(host, "r4h", base, cmd, N(cmd)); no_errors("r4h");
        diff("R4HT.TXT"); diff("R4HS.TXT"); diff("R4HC.TXT");
    }
    {   /* R4E1..R4E4: no-initial-eject reports in fresh sessions. */
        static const char *const e1[] = { "USE R4FLTB", "REPORT FORM FLT_INFO TO FILE E1" };
        static const char *const e2[] = { "USE R4FLTB", "? \"a\"", "? \"b\"", "? \"c\"", "? \"d\"", "? \"e\"", "REPORT FORM FLT_INFO TO FILE E2" };
        static const char *const e3[] = { "USE TRAVEL INDEX TRIPS", "REPORT FORM TRAVELER NEXT 3 TO FILE E3A", "USE R4FLTB", "REPORT FORM FLT_INFO TO FILE E3B" };
        static const char *const e4[] = { "USE R4FLTB", "REPORT FORM FLT_INFO TO FILE E4A", "REPORT FORM FLT_INFO TO FILE E4B" };
        printf("sessions R4E1..R4E4 (line count starts fresh without ALTERNATE):\n");
        session(host, "e1", base, e1, N(e1)); no_errors("e1"); diff("E1.TXT");
        session(host, "e2", base, e2, N(e2)); no_errors("e2"); diff("E2.TXT");
        session(host, "e3", base, e3, N(e3)); no_errors("e3"); diff("E3A.TXT"); diff("E3B.TXT");
        session(host, "e4", base, e4, N(e4)); no_errors("e4"); diff("E4A.TXT"); diff("E4B.TXT");
    }
    {   /* R4CT/R4CV/R4CF: lines-per-page sweeps (patched footer word 0x7B8). */
        static const struct { const char *dir, *use, *frm, *out, *opt; int lo, hi; } sw[] = {
            { "r4ct", "USE R4TRIP", "TP", "CTP", "", 14, 40 },
            { "r4ct", 0, "TP", "CTS", " SUMMARY", 14, 24 },
            { "r4cv", "USE TRAVEL INDEX TRIPS", "TV", "CTV", "", 18, 40 },
            { "r4cv", 0, "TV", "CTL", " PLAIN", 18, 25 },
            { "r4cf", "USE R4FLTB", "FL", "CFL", "", 11, 24 } };
        static char names[160][16];
        const char *in[200];
        const char *cmd[256];
        int s, j, k;
        printf("sessions R4CT/R4CV/R4CF (lines-per-page sweeps):\n");
        for (s = 0; s < N(sw); s++) {
            if (!sw[s].use) continue;
            for (k = 0; base[k]; k++) in[k] = base[k];
            n = 0;
            cmd[n++] = sw[s].use;
            for (j = s; j < N(sw) && (j == s || !sw[j].use); j++)
                for (i = sw[j].lo; i <= sw[j].hi; i++) {
                    if (!*sw[j].opt) { snprintf(names[k], 16, "%s%02d.FRM", sw[j].frm, i); in[k] = names[k]; k++; }
                    snprintf(g_cmd[n], sizeof g_cmd[n], "REPORT FORM %s%02d%s TO FILE %s%02d", sw[j].frm, i, sw[j].opt, sw[j].out, i);
                    cmd[n] = g_cmd[n]; n++;
                }
            in[k] = 0;
            session(host, sw[s].dir, in, cmd, n); no_errors(sw[s].dir);
            for (j = s; j < N(sw) && (j == s || !sw[j].use); j++)
                for (i = sw[j].lo; i <= sw[j].hi; i++) {
                    char o[24];
                    snprintf(o, sizeof o, "%s%02d.TXT", sw[j].out, i);
                    diff(o);
                }
        }
    }
    printf("refusals (catalog / manual grounded, no golden):\n");
    expect(host, base, "REPORT FORM TRAVELER TO PRINT", "126  Printer is either not connected or turned off.", "U7-16: TO PRINT refused, InitechOS has no printer");
    expect(host, base, "REPORT FORM NOSUCH", "1  File does not exist.", "missing .frm is #1");
    expect(host, base, "REPORT FORM UNIVERS", "50  Report file invalid.", "U7-17: corrupt UNIVERS.FRM control is #50");
    expect(host, base, "REPORT FORM ?", "36  Unrecognized phrase/keyword in command.", "? picklist refused #36");
    {
        static const char *const c[] = { "CLOSE DATABASES", "REPORT FORM TRAVELER" };
        session(host, "refuse", base, c, 2);
        CHECK(strstr(C.buf, "52  No database is in USE.") != NULL, "no table in USE is #52");
    }
    {   /* An unminted .frm option (double space 'Y' at 0x7C0) is refused. */
        FILE *f;
        session(host, "refuse", base, (const char *const *)0, 0);
        f = fopen("TRAVELER.FRM", "r+b");
        CHECK(f != NULL, "double-space fixture writable");
        if (f) { fseek(f, 0x7C0, SEEK_SET); fputc('Y', f); fclose(f); }
        {
            static const char *const c[] = { "USE TRAVEL INDEX TRIPS", "REPORT FORM TRAVELER" };
            const char *none[] = { 0 };
            session(host, "refuse", none, c, 2);
        }
        CHECK(strstr(C.buf, "50  Report file invalid.") != NULL, "unminted double-space flag refused #50, not guessed");
    }
    pal_host_free(host);
    return TEST_SUMMARY("test-samir-report");
}
