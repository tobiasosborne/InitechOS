/* test_samir_report.c -- host differential for SAMIR REPORT FORM (initech-airx).
 *
 * REAL-dBASE DIFFERENTIAL (Law 2): every expected byte is a file written by
 * real DBASE.EXE 1.1 under dosbox-x (mint session 004, recorded in
 * ../dbase3-decomp/re/mint-results-004.md; md5s pinned in
 * report_mint004.md5 and checked by the Makefile before this runs). SAMIR
 * replays the same command sequence (R4G/R4CT/R4CV/R4CF/R4D/R4E*.PRG) on
 * byte-identical copies of the same .dbf/.ndx/.dbt/.frm inputs, and each
 * REPORT FORM ... TO FILE output must equal the real file byte for byte
 * (CR LF lines, CR FF ejects, the closing ^Z). The console stream must carry
 * the same report without the FF bytes (real screen: R4S1..R4S3.PNG).
 * Nothing here is generated by SAMIR or by a model of it.
 *
 * Refusal checks are catalog/manual-grounded (no golden): DBASE.MSG #1, #36,
 * #50, #52, #126 (spec/samir/dbase_msg_codes.tsv; Using dBase III Plus
 * U5-177, U7-16, U7-17). UNIVERS.FRM is the corpus's real corrupt control.
 */
