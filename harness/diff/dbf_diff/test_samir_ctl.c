extern int samir_repl(samir_pal_t *pal, xb_interp *ip);

#define CAP_BUF 262144
#define MAXL    16
#define MAXESC  4

typedef struct {
    samir_pal_t  pal;            /* MUST be first */
    samir_pal_t *inner;
    char         buf[CAP_BUF];
    uint32_t     len;
    const char  *lines[MAXL];
    int          nlines, lineidx;
    const char  *keys;           /* conin_char answers, in order */
    long         esc_at[MAXESC]; /* poll ordinals that report Esc */
    int          nesc, escidx;
    long         polls;
} cap_pal;
static cap_pal g;

static pal_fd  c_open (samir_pal_t *p, const char *n, int m) { return ((cap_pal*)p)->inner->open(((cap_pal*)p)->inner,n,m); }
static int     c_close(samir_pal_t *p, pal_fd fd) { return ((cap_pal*)p)->inner->close(((cap_pal*)p)->inner,fd); }
static int32_t c_read (samir_pal_t *p, pal_fd fd, void *b, uint32_t n) { return ((cap_pal*)p)->inner->read(((cap_pal*)p)->inner,fd,b,n); }
static int32_t c_write(samir_pal_t *p, pal_fd fd, const void *b, uint32_t n) { return ((cap_pal*)p)->inner->write(((cap_pal*)p)->inner,fd,b,n); }
static int32_t c_seek (samir_pal_t *p, pal_fd fd, int32_t o, int w) { return ((cap_pal*)p)->inner->seek(((cap_pal*)p)->inner,fd,o,w); }
static int     c_remove(samir_pal_t *p, const char *n) { return ((cap_pal*)p)->inner->remove(((cap_pal*)p)->inner,n); }
static int     c_rename(samir_pal_t *p, const char *f, const char *t) { return ((cap_pal*)p)->inner->rename(((cap_pal*)p)->inner,f,t); }
static void    c_conout(samir_pal_t *p, const char *s, uint32_t n)
{
    cap_pal *c = (cap_pal*)p;
    uint32_t i;
    for (i = 0; i < n && c->len < CAP_BUF - 1u; i++) c->buf[c->len++] = s[i];
    c->buf[c->len] = '\0';
}
static int32_t c_conin_line(samir_pal_t *p, char *buf, uint32_t cap)
{
    cap_pal *c = (cap_pal*)p;
    const char *s;
    uint32_t k = 0;
    if (c->lineidx >= c->nlines) { buf[0] = '\0'; return -1; }
    s = c->lines[c->lineidx++];
    while (s[k] && k < cap - 1u) { buf[k] = s[k]; k++; }
    buf[k] = '\0';
    return (int32_t)k;
}
static int32_t c_conin_char(samir_pal_t *p)
{
    cap_pal *c = (cap_pal*)p;
    if (!c->keys || !*c->keys) return -1;
    return (int32_t)(unsigned char)*c->keys++;
}
static int c_conin_escape(samir_pal_t *p)
{
    cap_pal *c = (cap_pal*)p;
    c->polls++;
    if (c->escidx < c->nesc && c->polls >= c->esc_at[c->escidx]) {
        c->escidx++;
        c->polls = 0;
        return 1;
    }
    return 0;
}
static int  c_curdrive(samir_pal_t *p) { (void)p; return 'C'; }  /* the mint's C: */
static void c_gotoxy(samir_pal_t *p, uint8_t r, uint8_t col) { ((cap_pal*)p)->inner->gotoxy(((cap_pal*)p)->inner,r,col); }
static void c_set_attr(samir_pal_t *p, uint8_t a) { ((cap_pal*)p)->inner->set_attr(((cap_pal*)p)->inner,a); }
static void c_today(samir_pal_t *p, uint8_t *y, uint8_t *m, uint8_t *d) { ((cap_pal*)p)->inner->today(((cap_pal*)p)->inner,y,m,d); }
static void *c_alloc(samir_pal_t *p, uint32_t n) { return ((cap_pal*)p)->inner->alloc(((cap_pal*)p)->inner,n); }
static void c_reset(samir_pal_t *p, void *m) { ((cap_pal*)p)->inner->reset(((cap_pal*)p)->inner,m); }
static void *c_acquire(samir_pal_t *p, uint32_t n) { return ((cap_pal*)p)->inner->acquire(((cap_pal*)p)->inner,n); }
static void c_release(samir_pal_t *p, void *m) { ((cap_pal*)p)->inner->release(((cap_pal*)p)->inner,m); }

static samir_pal_t *cap_make(samir_pal_t *inner)
{
    memset(&g, 0, sizeof g);
    g.inner = inner;
    g.pal.open = c_open; g.pal.close = c_close; g.pal.read = c_read;
    g.pal.write = c_write; g.pal.seek = c_seek; g.pal.remove = c_remove;
    g.pal.rename = c_rename; g.pal.conout = c_conout;
    g.pal.conin_line = c_conin_line; g.pal.conin_char = c_conin_char;
    g.pal.gotoxy = c_gotoxy; g.pal.set_attr = c_set_attr; g.pal.today = c_today;
    g.pal.alloc = c_alloc; g.pal.reset = c_reset;
    g.pal.acquire = c_acquire; g.pal.release = c_release;
    g.pal.conin_escape = c_conin_escape; g.pal.curdrive = c_curdrive;
    return &g.pal;
}

static const char *g_corpus;
static const char *g_case = "";

/* A session that never finishes is the L002 bug itself (an unstoppable
 * loop): fail it loudly instead of hanging the gate. */
static void on_alarm(int sig)
{
    (void)sig;
    fprintf(stderr, "  FAIL %s: session did not finish in 20 s (unstoppable program)\n", g_case);
    printf("test-samir-ctl: %d checks, %d failures\n", g_checks + 1, g_fails + 1);
    fflush(stdout);
    _exit(1);
}

static int slurp(const char *name, char *out, size_t cap)
{
    char path[1200];
    FILE *f;
    size_t n;
    snprintf(path, sizeof path, "%s/%s", g_corpus, name);
    f = fopen(path, "rb");
    if (!f) { fprintf(stderr, "missing corpus file %s\n", path); return -1; }
    n = fread(out, 1, cap - 1, f);
    fclose(f);
    out[n] = '\0';
    return (int)n;
}

static int corpus_has(const char *prg)
{
    char probe[1200];
    FILE *t;
    snprintf(probe, sizeof probe, "%s/%s.PRG", g_corpus, prg);
    t = fopen(probe, "rb");
    if (t) fclose(t);
    return t != NULL;
}

/* Collect every "DO <file>" target of `text` that is a corpus program file
 * (not DO WHILE / DO CASE, not already listed). */
static void scan_do(const char *text, char list[][16], int *n, int max)
{
    const char *q;
    for (q = text; (q = strstr(q, "DO ")) != NULL; q += 3) {
        char tgt[16];
        int j;
        if (q != text && q[-1] != '\n' && q[-1] != ' ') continue;
        if (sscanf(q + 3, "%15[A-Za-z0-9_]", tgt) != 1) continue;
        if (!strcmp(tgt, "WHILE") || !strcmp(tgt, "CASE") || !corpus_has(tgt)) continue;
        for (j = 0; j < *n; j++) if (!strcmp(list[j], tgt)) break;
        if (j == *n && *n < max) snprintf(list[(*n)++], 16, "%s", tgt);
    }
}

/* Stage NAME.PRG from the corpus into build/samir.ctl/ by the rules above. */
static int g_pad;      /* lines of "X=1" appended to each procedure file */

static int stage_as(const char *name, const char *as)
{
    static char src[16384], dst[65536], sub[16384];
    char path[256], procf[8][16], progs[8][16];
    char *p = src;
    size_t k = 0;
    int nproc = 0, nprog = 1, i;
    FILE *f;
    snprintf(path, sizeof path, "%s.PRG", name);
    if (slurp(path, src, sizeof src) < 0) return -1;
    snprintf(progs[0], 16, "%s", name);         /* never re-append the main */
    while (*p) {
        char *e = p, save;
        while (*e && *e != '\n') e++;
        if (*e) e++;
        save = *e; *e = '\0';
        if (!strncmp(p, "SET ALTERNATE", 13) || !strncmp(p, "RUN AUTOTYPE", 12) ||
            !strncmp(p, "CLOSE PROCEDURE", 15)) {
            /* mint harness line: dropped */
        } else if (!strncmp(p, "SET PROCEDURE TO ", 17)) {
            if (nproc < 8 && sscanf(p + 17, "%15[A-Za-z0-9_]", procf[nproc]) == 1) nproc++;
        } else {
            k += (size_t)snprintf(dst + k, sizeof dst - k, "%s", p);
        }
        *e = save;
        p = e;
    }
    for (i = 0; i < nproc; i++) {               /* procedure files: verbatim */
        int j;
        size_t sl;
        snprintf(path, sizeof path, "%s.PRG", procf[i]);
        if (slurp(path, sub, sizeof sub) < 0) return -1;
        sl = strlen(sub);
        /* NESTBIG padding goes before the procedure's closing RETURN. */
        if (g_pad && sl > 8 && !strcmp(sub + sl - 8, "RETURN\r\n")) sub[sl - 8] = '\0';
        k += (size_t)snprintf(dst + k, sizeof dst - k, "%s", sub);
        for (j = 0; j < g_pad; j++) k += (size_t)snprintf(dst + k, sizeof dst - k, "X=1\r\n");
        if (g_pad) k += (size_t)snprintf(dst + k, sizeof dst - k, "RETURN\r\n");
    }
    scan_do(src, progs, &nprog, 8);
    for (i = 1; i < nprog; i++) {               /* program files: as PROCEDUREs */
        snprintf(path, sizeof path, "%s.PRG", progs[i]);
        if (slurp(path, sub, sizeof sub) < 0) return -1;
        k += (size_t)snprintf(dst + k, sizeof dst - k, "PROCEDURE %s\r\n%s", progs[i], sub);
        scan_do(sub, progs, &nprog, 8);
    }
    snprintf(path, sizeof path, "build/samir.ctl/%s.PRG", as);
    f = fopen(path, "wb");
    if (!f) return -1;
    fwrite(dst, 1, k, f);
    fclose(f);
    return 0;
}

/* The real transcript with ^Z dropped and typed-command echoes as prompts. */
static void golden(const char *txt, char *out, size_t cap)
{
    char raw[16384];
    size_t i, k = 0;
    int n = slurp(txt, raw, sizeof raw);
    CHECK(n >= 0, "real dBASE transcript present in the corpus");
    if (n < 0) { out[0] = '\0'; return; }
    for (i = 0; raw[i] && k + 1 < cap; i++) {
        if (raw[i] == 0x1a) continue;
        if (raw[i] == '.' && raw[i + 1] == ' ' && (i == 0 || raw[i - 1] == '\n')) {
            /* ". <typed command>\r\n" -> ". " */
            out[k++] = '.'; out[k++] = ' ';
            i += 2;
            while (raw[i] && raw[i] != '\n') i++;
            continue;
        }
        out[k++] = raw[i];
    }
    out[k] = '\0';
}

/* Run the dot prompt over `lines` (DO <as> first; <as> is <name> staged). */
static void session_as(const char *name, const char *as, const char *const *lines,
                       int n, const char *keys, const long *esc, int nesc)
{
    char cwd[1024], doline[32];
    xb_interp *ip;
    int i;
    const char *nm = as;
    g_case = as;
    alarm(20);
    CHECK(stage_as(name, as) == 0, "corpus program staged");
    g.len = 0; g.buf[0] = '\0';
    g.nlines = 0; g.lineidx = 0;
    snprintf(doline, sizeof doline, "DO %s", nm);
    g.lines[g.nlines++] = strdup(doline);
    for (i = 0; i < n && g.nlines < MAXL; i++) g.lines[g.nlines++] = lines[i];
    g.keys = keys;
    g.nesc = nesc; g.escidx = 0; g.polls = 0;
    for (i = 0; i < nesc; i++) g.esc_at[i] = esc[i];
    CHECK(getcwd(cwd, sizeof cwd) != NULL && chdir("build/samir.ctl") == 0, "session dir");
    ip = xb_interp_make(&g.pal);
    CHECK(ip != NULL, "interpreter constructed");
    if (ip) {
        CHECK(samir_repl(&g.pal, ip) == 0, "REPL returns cleanly (session survived)");
        xb_interp_free(ip);
    }
    CHECK(chdir(cwd) == 0, "session dir left");
    alarm(0);
    free((void *)g.lines[0]);
    if (getenv("CTL_TRACE")) fprintf(stderr, "---- %s ----\n%s\n", name, g.buf);
}

static void session(const char *name, const char *const *lines, int n,
                    const char *keys, const long *esc, int nesc)
{
    session_as(name, name, lines, n, keys, esc, nesc);
}

/* NESTBIG runs on a thread whose stack is NESTBIG_STACK bytes, a stand-in for
 * the 64 KiB SAMIR.COM stack (spec/memory_map.h PROGRAM_STACK_BOT..TOP; host
 * frames are larger, 64-bit). Per-call line tables back on the stack
 * (FLOW_MUTATE_STACK_LINES: 20 levels x 503 lines x 16 bytes) overflow it;
 * the overflow is caught on an alternate signal stack and reported RED. */
#define NESTBIG_STACK (192u * 1024u)
static void on_segv(int sig)
{
    (void)sig;
    fprintf(stderr, "  FAIL %s: stack overflow (SIGSEGV) -- the session was lost\n", g_case);
    printf("test-samir-ctl: %d checks, %d failures\n", g_checks + 1, g_fails + 1);
    fflush(stdout);
    _exit(1);
}
static char g_alt[65536];
static void *nestbig_thread(void *u)
{
    stack_t ss;
    (void)u;
    ss.ss_sp = g_alt; ss.ss_size = sizeof g_alt; ss.ss_flags = 0;
    CHECK(sigaltstack(&ss, (stack_t *)0) == 0, "alternate signal stack");
    session_as("NEST", "NESTBIG", (const char *const *)0, 0, "", (const long *)0, 0);
    return (void *)0;
}
static void nestbig_on_small_stack(void)
{
    pthread_attr_t at;
    pthread_t th;
    struct sigaction sa;
    memset(&sa, 0, sizeof sa);
    sa.sa_handler = on_segv;
    sa.sa_flags = SA_ONSTACK;
    CHECK(sigaction(SIGSEGV, &sa, (struct sigaction *)0) == 0, "SIGSEGV handler");
    CHECK(pthread_attr_init(&at) == 0 &&
          pthread_attr_setstacksize(&at, NESTBIG_STACK) == 0, "small-stack thread attr");
    CHECK(pthread_create(&th, &at, nestbig_thread, (void *)0) == 0, "NESTBIG thread");
    pthread_join(th, (void **)0);
    pthread_attr_destroy(&at);
}

static void expect_in(const char *want, const char *why)
{
    int ok = strstr(g.buf, want) != NULL;
    CHECK(ok, why);
    if (!ok) fprintf(stderr, "--- real (want) ---\n%s\n--- samir ---\n%s\n", want, g.buf);
}

/* the block of `gold` from its first `from` through the end of `upto`. */
static void cut(const char *gold, const char *from, const char *upto,
                char *out, size_t cap)
{
    const char *a = strstr(gold, from), *b;
    out[0] = '\0';
    CHECK(a != NULL, "golden contains the graded block start");
    if (!a) return;
    b = strstr(a, upto);
    CHECK(b != NULL, "golden contains the graded block end");
    if (!b) return;
    b += strlen(upto);
    snprintf(out, cap, "%.*s", (int)(b - a), a);
}

int main(int argc, char **argv)
{
    struct pal_host_cfg cfg = {86, 7, 24, 16u * 1024u * 1024u};
    samir_pal_t *host;
    static char gold[16384], want[16384];
    if (argc < 2) { fprintf(stderr, "usage: %s SAMIRCTL_MINT_DIR\n", argv[0]); return 2; }
    g_corpus = argv[1];
    signal(SIGALRM, on_alarm);
    host = pal_host_make(cfg);
    if (!host) return 2;
    cap_make(host);
    mkdir("build/samir.ctl", 0777);

    /* L002: Esc twice in DO WHILE .T.: Ignore resumes, Cancel unwinds. */
    {
        static const char *const l[] = {"QUIT"};
        static const long e[] = {40, 40};
        golden("ESC.TXT", gold, sizeof gold);
        cut(gold, "*** INTERRUPTED ***", "Do cancelled\r\n", want, sizeof want);
        session("ESC", l, 1, "IC", e, 2);
        expect_in(want, "L002 Esc/Ignore/Esc/Cancel transcript == real III+ (ESC.TXT)");
        CHECK(!strstr(g.buf, "NOTREACHED"), "L002 Cancel abandons the program");
        CHECK(g.lineidx == 2, "L002 the dot prompt took the next command (session alive)");
    }
    /* Suspend -> nested dot prompt -> RESUME -> Esc -> Cancel. */
    {
        static const char *const l[] = {"RESUME", "QUIT"};
        static const long e[] = {40, 40};
        golden("ESCS.TXT", gold, sizeof gold);
        cut(gold, "*** INTERRUPTED ***", "Do cancelled\r\n", want, sizeof want);
        session("ESCS", l, 2, "SC", e, 2);
        expect_in(want, "L002 Esc/Suspend/RESUME/Esc/Cancel == real III+ (ESCS.TXT)");
    }
    /* ON ESCAPE trap ends the loop. */
    {
        static const long e[] = {40};
        golden("ESCTRAP.TXT", gold, sizeof gold);
        cut(gold, "\r\nTRAPPED", ".T.", want, sizeof want);
        session("ESCTRAP", (const char *const *)0, 0, "", e, 1);
        expect_in(want, "L002 ON ESCAPE runs and ends the loop (ESCTRAP.TXT)");
        CHECK(!strstr(g.buf, "INTERRUPTED"), "ON ESCAPE replaces the interrupt prompt");
    }
    /* L003: recursion stops at 20 DO levels with #103, session intact. */
    {
        golden("NEST.TXT", gold, sizeof gold);
        cut(gold, "\r\nTRAP", "UNWOUND         19", want, sizeof want);
        session("NEST", (const char *const *)0, 0, "", (const long *)0, 0);
        expect_in(want, "L003 20-level DO cap: TRAP 19 103 DOs nested too deep. (NEST.TXT)");
        g_pad = 500;
        nestbig_on_small_stack();
        g_pad = 0;
        expect_in(want, "L003 500-line recursive body: same TRAP 19 103 / UNWOUND 19 (NEST.TXT)");
    }
    {
        static const char *const l[] = {"? N", "QUIT"};
        session("RAW", l, 2, "", (const long *)0, 0);
        expect_in("DOs nested too deep.", "L003 untrapped: the #103 message (RAW.TXT line 1)");
        expect_in("\r\n        19", "L003 untrapped: 19 levels ran (RAW.TXT: 19 RAWP frames)");
        CHECK(!strstr(g.buf, "AFTER"), "L003 untrapped error ends the program (Do cancelled)");
    }
    /* L041 RETURN TO MASTER. */
    {
        golden("MASTER.TXT", gold, sizeof gold);
        session("MASTER", (const char *const *)0, 0, "", (const long *)0, 0);
        expect_in(gold, "L041 RETURN TO MASTER == real III+ (MASTER.TXT)");
        CHECK(!strstr(g.buf, "FIRST RESUMED"), "L041 intermediate frame discarded");
    }
    /* L013 QUIT inside a program. */
    {
        static const char *const l[] = {"? \"STILL HERE\"", "QUIT"};
        golden("QUITP.TXT", gold, sizeof gold);
        session("QUITP", l, 2, "", (const long *)0, 0);
        expect_in(gold, "L013 QUIT program prints BEFORE QUIT (QUITP.TXT)");
        CHECK(!strstr(g.buf, "AFTER QUIT"), "L013 nothing after QUIT runs");
        CHECK(!strstr(g.buf, "Unrecognized"), "L013 QUIT is a recognised program verb");
        CHECK(!strstr(g.buf, "STILL HERE") && g.lineidx == 1,
              "L013 QUIT left SAMIR (the next dot-prompt line is never read)");
    }
    /* L022 RETRY from an ON ERROR handler. */
    {
        golden("RETRYM.TXT", gold, sizeof gold);
        session("RETRYM", (const char *const *)0, 0, "", (const long *)0, 0);
        expect_in(gold, "L022 RETRY re-runs ? XX+1 -> 7, DONE 1 (RETRYM.TXT)");
    }
    pal_host_free(host);
    return TEST_SUMMARY("test-samir-ctl");
}
