/* test_samir_ctl.c -- SAMIR program-control oracle (initech-39e5).
 *
 * REAL-dBASE DIFFERENTIAL. The programs are the corpus PRGs real DBASE.EXE
 * 1.1 ran under dosbox-x in mint session "samirctl" (2026-10-23, this bead):
 *   harness/diff/dbf_diff/xbase_prog_diff/samirctl-mint/{ESC,ESCS,ESCTRAP,
 *   NEST,RAW,MASTER,QUITP,RETRYM}.PRG (+ NESTP/RAWP/FIRST/SECOND/ERH.PRG;
 *   recipe in its README), and every expected byte is cut from the SET
 *   ALTERNATE transcript real dBASE wrote (ESC.TXT, ...), md5-pinned by
 *   samirctl-mint/samirctl_mint.md5 before this runs. Nothing here is
 *   generated by SAMIR. Audit 2026-10-23-samir findings covered:
 *   L002 (Esc cannot stop a loop), L003 (recursion destroys the session),
 *   L041 (RETURN TO MASTER one level), L013 (QUIT in a PRG rejected),
 *   L022 (RETRY does not retry). Manual: Using III+ U5-220 SET ESCAPE,
 *   U5-160 ON, U5-273 SUSPEND, U5-182 RETRY, U5-183 RETURN, U5-168 QUIT,
 *   U7-4 [103] "DOs nested too deep." (20 nested DOs).
 *
 * Staging rules (the only transformations; documented here and in the
 * Makefile comment):
 *  - mint-harness lines are dropped: SET ALTERNATE ..., RUN AUTOTYPE ...
 *    (the dosbox-x keystroke injector), CLOSE PROCEDURE;
 *  - III+ 1.1 keeps procedures in separate files (SET PROCEDURE TO / one
 *    .PRG per routine); SAMIR's model is PROCEDURE blocks in the program
 *    file (control-flow-and-procedures.md sec 7). "SET PROCEDURE TO X" is
 *    dropped and X.PRG appended; a DOne program file Y.PRG is appended as
 *    "PROCEDURE Y" + its text. The "Called from - C:<file>.prg" trace is
 *    therefore only graded on programs without such routines (ESC/ESCS);
 *  - the keystrokes autotype sent are replayed: Esc through the PAL's
 *    conin_escape (after a fixed number of statement polls -- the loop
 *    count at the press is not observable in the transcript), the C/I/S
 *    answers through conin_char, typed dot-prompt commands through
 *    conin_line;
 *  - a typed command's echo in the log (". resume" + CR LF) is the dot
 *    prompt ". " in the capture (the host console does not echo input);
 *  - CR LF and the closing ^Z are compared as written (^Z dropped);
 *  - NESTBIG (initech-39e5 review): NEST with 500 "X=1" lines appended to
 *    its recursive procedure -- assignments to an unused variable that
 *    print nothing, so the real NEST.TXT transcript still grades it. It
 *    proves a 500-line body recursing to the 20-level cap leaves the session
 *    intact (its line tables come from the PAL heap, not the stack).
 */
