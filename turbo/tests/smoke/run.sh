#!/bin/sh
# The product boot image is read-only input. TEST is a fresh separate volume;
# mtools is the independent reader of files created by the guest compiler.
set -eu
cd "$(dirname "$0")/../../.."
root=$PWD
out=$root/build/turbo/smoke
mkdir -p "$out"
export INITECH_TEST_RAM_MB=8 INITECH_QMP_STDIO=1 MTOOLS_SKIP_CHECK=1
for emulator in qemu bochs; do
 dir=$out/$emulator
 mkdir -p "$dir/host"
 disk=$dir/test.img
 dd if=/dev/zero of="$disk" bs=512 count=2880 2>/dev/null
 mformat -i "$disk" -f 1440 -N 0x54555242 -v TEST ::
 mcopy -i "$disk" build/dos/COMMAND.COM ::
 mcopy -i "$disk" build/turbo/compiler/TURBO.COM ::
 mcopy -i "$disk" turbo/compiler/fixtures/gen_control_deep.pas ::TURBOIN.PAS
 printf 'FILES=20\r\nSHELL=COMMAND.COM /P\r\n' > "$dir/CONFIG.SYS"
 mcopy -i "$disk" "$dir/CONFIG.SYS" ::
 printf '@echo off\r\nturbo\r\necho\r\necho turbo-smoke-complete\r\n' > "$dir/RUN.BAT"
 mcopy -i "$disk" "$dir/RUN.BAT" ::
 cp turbo/compiler/fixtures/gen_control_deep.pas "$dir/host/TURBOIN.PAS"
 (cd "$dir/host" && "$root/build/turbo/compiler/turbo_fpc" > transcript)
 printf '\n\nrun\n' | build/factory/keys > "$dir/keys"
 extra=
 if [ "$emulator" = bochs ]; then extra='--vga-ext none'; fi
 start=$(date +%s)
 if ! build/factory/${emulator}_harness --disk build/image/boot.img --disk2 "$disk" \
     $extra --keys-after SHELL-READY --keys "$(cat "$dir/keys")" \
     --expect turbo-smoke-complete --quit-after turbo-smoke-complete \
     --timeout-ms 180000 --name run --out "$dir" > "$dir/stdout" 2> "$dir/report"; then
     cat "$dir/report"; exit 1
 fi
 elapsed=$(($(date +%s)-start))
 tr -d '\r' < "$dir/run.serial" > "$dir/serial.txt"
 if grep -E 'TURBO-.*(ERROR|SKIP)|PANIC|Bad command|File not found' "$dir/serial.txt"; then exit 1; fi
 mcopy -o -i "$disk" ::TURBOOUT.S "$dir/guest.s"
 cmp "$dir/host/TURBOOUT.S" "$dir/guest.s"
 if [ "$emulator" = qemu ]; then
  grep -F 'triple_fault=0 cpu_reset=2 guest_errors=0' "$dir/report"
  test "$(grep -c 'CPU Reset' "$dir/run.qemu.log")" -eq 2
 fi
 echo "$emulator: extended TURBO.COM generated byte-identical assembly; session=${elapsed}s"
done
