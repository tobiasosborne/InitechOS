#!/bin/sh
set -eu
out=$1 source=$2 compiler=$3
. "$TOP/turbo/tests/checks.sh"
compile_cli() {
 cli_dir=$1; shift
 cli_rc=0
 (cd "$cli_dir" && "$compiler" "$@" > transcript) || cli_rc=$?
 case $cli_rc in
  0) return 0;;
  1) grep -E '^TURBO-.*ERROR' "$cli_dir/transcript" > /dev/null || return 2; return 1;;
  *) return 2;;
 esac
}
setup mkdir -p "$out/plain" "$out/dump" "$out/dos" "$out/lf"
setup cp fixtures/gen_tiny.pas "$out/plain/INPUT.PAS"
setup cp fixtures/gen_tiny.pas "$out/dump/INPUT.PAS"
assert 'selected source compiles' compile_cli "$out/plain" INPUT.PAS
assert_not 'file argument omits lexer and parser dumps' grep -E 'TURBO-(LEX|PARSE)-(BEGIN|END)' "$out/plain/transcript"
assert 'ordinary compilation creates no assembly dump (MINT07 disk read-back)' test ! -e "$out/plain/TURBOOUT.S"
assert 'dump mode source compiles' compile_cli "$out/dump" /DUMP INPUT.PAS
assert 'explicit dump switch retains host protocol' grep -Fx TURBO-LEX-BEGIN "$out/dump/transcript"
assert 'dump switch does not change generated bytes' cmp "$out/plain/TURBOOUT.EXE" "$out/dump/TURBOOUT.EXE"
setup env LC_ALL=C awk '{printf "%s\r\n",$0} END{printf "%c",26}' "$source" > "$out/dos/INPUT.PAS"
assert 'DOS-saved proved source fits input capacity' test "$(wc -c < "$out/dos/INPUT.PAS")" -le 262144
assert 'DOS-saved compiler source compiles' compile_cli "$out/dos" INPUT.PAS
assert 'DOS CRLF and EOF marker are accepted' grep -F 'TURBO-NATIVE-OK form=1 ' "$out/dos/transcript"
assert_not 'DOS-saved source has no compile errors' grep -E 'TURBO-.*(ERROR|SKIP)' "$out/dos/transcript"
setup cp "$source" "$out/lf/INPUT.PAS"
assert 'LF compiler source compiles' compile_cli "$out/lf" INPUT.PAS
assert 'LF and DOS-saved source produce identical whole containers' cmp "$out/lf/TURBOOUT.EXE" "$out/dos/TURBOOUT.EXE"
for alias in TURBOOUT.COM TURBOOUT.EXE TURBOOUT.S; do
 dir=$out/alias-$alias
 setup mkdir -p "$dir"
 setup cp fixtures/gen_tiny.pas "$dir/$alias"
 alias_rc=0
 if [ "$alias" = TURBOOUT.S ]; then compile_cli "$dir" /DUMP "$alias" || alias_rc=$?
 else compile_cli "$dir" "$alias" || alias_rc=$?; fi
 case $alias_rc in 0|1) :;; *) echo 'ERROR alias compiler run' >&2; exit 2;; esac
 assert "output alias:$alias retains source bytes" cmp fixtures/gen_tiny.pas "$dir/$alias"
 assert "output alias:$alias is refused" test "$alias_rc" -eq 1
done
for fixture in fixtures/gen*.pas; do
 name=$(basename "$fixture" .pas)
 dir=$out/modes-$name
 setup mkdir -p "$dir"
 setup cp "$fixture" "$dir/INPUT.PAS"
 assert "$name:factory mode compiles" compile_cli "$dir" /DUMP INPUT.PAS
 setup cp "$dir/TURBOOUT.EXE" "$dir/dump.exe"
 setup cp "$dir/TURBOOUT.COM" "$dir/dump.com"
 assert "$name:native-only mode compiles" compile_cli "$dir" INPUT.PAS
 assert "$name:EXE invariant across dump switch" cmp "$dir/dump.exe" "$dir/TURBOOUT.EXE"
 assert "$name:COM invariant across dump switch" cmp "$dir/dump.com" "$dir/TURBOOUT.COM"
done
finish
