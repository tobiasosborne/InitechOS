/* Deterministic byte-pair storage for the locked III+ DBASE.MSG catalogue.
 * Storage only: no text/ordinal changes. PRD 6.6, spec/samir/README.md.
 * Pairs only refer to ASCII or earlier pairs; zero separates messages.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

int main(int argc, char **argv)
{
    unsigned char text[16384], pairs[128][2];
    static unsigned counts[256][256];
    char line[1024];
    unsigned n = 1, ordinal = 1, nt = 0, i, a, b;
    FILE *f;
    if (argc != 2 || !(f = fopen(argv[1], "rb"))) return 2;
    text[0] = 0; /* ordinal zero */
    while (fgets(line, sizeof line, f)) {
        char *tab, *end;
        unsigned code;
        if (line[0] == '#' || !strncmp(line, "code\t", 5)) continue;
        tab = strchr(line, '\t');
        if (!tab) return 2;
        code = (unsigned)strtoul(line, &end, 10);
        if (end != tab || code != ordinal++) return 2;
        end = tab + 1;
        end[strcspn(end, "\r\n")] = 0;
        for (i = 0; end[i]; i++) {
            unsigned c = (unsigned char)end[i];
            if (c < 32 || c > 126 || n >= sizeof text - 1) return 2;
            text[n++] = (unsigned char)c;
        }
        text[n++] = 0;
    }
    if (ferror(f) || fclose(f) || ordinal != 152) return 2;
    while (nt < 128) {
        unsigned best = 0, ba = 0, bb = 0, w = 0;
        memset(counts, 0, sizeof counts);
        for (i = 0; i + 1 < n; i++)
            if (text[i] && text[i + 1]) counts[text[i]][text[i + 1]]++;
        for (a = 1; a < 128 + nt; a++) for (b = 1; b < 128 + nt; b++)
            if (counts[a][b] > best) { best = counts[a][b]; ba = a; bb = b; }
        if (best <= 2) break;
        pairs[nt][0] = (unsigned char)ba;
        pairs[nt][1] = (unsigned char)bb;
        for (i = 0; i < n; i++) {
            if (i + 1 < n && text[i] == ba && text[i + 1] == bb) {
                text[w++] = (unsigned char)(128 + nt);
                i++;
            } else text[w++] = text[i];
        }
        n = w;
        nt++;
    }
    puts("/* Generated by tools/samir_msg_pack.c from spec/samir/dbase_msg_codes.tsv. */");
    puts("/* ASCII source; deterministic pair order; no runtime file dependency. */");
    puts("#ifndef SAMIR_MESSAGES_PACKED_H\n#define SAMIR_MESSAGES_PACKED_H");
    printf("#define SAMIR_MSG_PAIRS %u\n", nt);
    puts("static const unsigned char samir_msg_pairs[SAMIR_MSG_PAIRS][2] = {");
    for (i = 0; i < nt; i++) printf("    {%u, %u},\n", pairs[i][0], pairs[i][1]);
    puts("};\nstatic const unsigned char samir_msg_data[] = {");
    for (i = 0; i < n; i++) {
        if (!(i % 16)) fputs("    ", stdout);
        printf("%u,%s", text[i], (i % 16 == 15 || i + 1 == n) ? "\n" : " ");
    }
    puts("};\n#endif");
    return ferror(stdout) ? 2 : 0;
}
