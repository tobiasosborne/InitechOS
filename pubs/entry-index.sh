#!/bin/sh
# entry-index.sh -- print the sorted \input index of one manual entry directory
# (F4, initech-0wox2).  Usage: entry-index.sh <entries dir>, e.g.
#   pubs/manuals/initechbase-volume-one/entries/fn
# Every entry lives in its own file <key>.tex; the index lists them in
# byte order (LC_ALL=C) of <key>, so adding an entry is adding ONE file and no
# shared line.  Key conventions (see docs/plans/INITECHBASE-lane-howto.md):
#   lower-case name, blanks as '-', SET options 'set-<name>', symbols '0q' (?),
#   '0qq' (??), '0amp' (&) so they sort first.  \input paths are relative to
#   the manual directory, which is where build.sh runs LaTeX.
# Thin shell (Law 3); deterministic output (Rule 11): no dates, no host paths.
set -eu
export LC_ALL=C
dir=$1
rel=${dir#*/manuals/*/}
[ -d "$dir" ] || { printf '!!! entry-index FAIL: %s is not a directory\n' "$dir" >&2; exit 1; }
# Validate outside the pipeline: a subshell failure must not be hidden by sort
# or the final reader, and invalid names must never emit partial TeX.
for f in "$dir"/*.tex; do
    [ -f "$f" ] || continue
    b=${f##*/}
    k=${b%.tex}
    case $k in ''|*[!A-Za-z0-9_-]*)
        printf '!!! entry-index FAIL: invalid entry key: %s\n' "$b" >&2
        exit 1;;
    esac
done
printf '%% Generated by pubs/entry-index.sh from %s -- do not edit.\n' "$rel"
for f in "$dir"/*.tex; do
    [ -f "$f" ] || continue
    b=${f##*/}
    printf '%s\n' "${b%.tex}"
done | LC_ALL=C sort | while IFS= read -r k; do
    printf '\\input{%s/%s}%%\n' "$rel" "$k"
done
