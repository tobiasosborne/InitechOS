; overlay_hdr.asm -- the header of C:\FLAIR.OVL (ADR-0014 DEC-14-2; epic
; initech-x8gsi lane 1). Layout = spec/overlay_format.h, field for field.
; Linked FIRST by os/milton/overlay.ld at OVERLAY_BASE, against the running
; kernel's symbols (ld --just-symbols), so every import dd below is the
; address in THAT kernel build. identity and crc32 are assembled as zero and
; filled by the factory packer (tools/flairovl.c) after the link. The kernel
; checks all of it before any section byte runs (Rule 2). ASCII only (Rule 12).
bits 32
section .ovl_hdr progbits alloc noexec nowrite align=4

extern _ovl_cold_start
extern _ovl_cold_off
extern _ovl_cold_len
extern _ovl_cold_bss_end
extern _ovl_image_len
; GENERATED by the Makefile's OVL rules from the objects (never hand-kept;
; the initech-13ig lesson): one `extern` per kernel import and per export,
; plus %define OVL_N_IMPORTS / OVL_N_EXPORTS.
%include "ovl_imports_ext.inc"
; MUTANT (Rule 6; the FOREIGN import-skew panic leg only): the LAST import
; address is offset by this, so the kernel must refuse on the import it
; would otherwise never look at (the TRANSIENT_LAST_IMPORT_SKEW pattern).
%ifndef OVL_LAST_IMPORT_SKEW
%define OVL_LAST_IMPORT_SKEW 0
%endif

global ovl_hdr
ovl_hdr:
    db 'FLAIROVL'                      ; magic (OVL_MAGIC)
    dd 1                               ; version (OVL_VERSION)
    dd 0                               ; identity (packer)
    dd 1                               ; n_sections
    dd OVL_N_IMPORTS                   ; n_imports (generated)
    dd OVL_N_EXPORTS                   ; n_exports (generated)
    dd _ovl_image_len                  ; image_len (before sector padding)
    ; directory[0]: section COLD (OVL_SECTION_COLD, OVL_FLAG_PRELOAD)
    dw 1, 1
    dd _ovl_cold_start                  ; load
    dd _ovl_cold_off                    ; file_off (OVL_SECTION_LOAD_RULE)
    dd _ovl_cold_len                    ; length on disk
    dd _ovl_cold_bss_end                ; bss_end
%include "ovl_imports_dd.inc"          ; dd <import> ... (generated; last + skew)
%include "ovl_exports_dd.inc"          ; dd <export> ... (generated, stub order)
    dd 0                               ; crc32 (packer; OVL_CRC_RULE)

section .note.GNU-stack noalloc noexec nowrite progbits
