; transient_hdr.asm -- the header of the TRANSIENT COMMAND.COM (bead
; initech-3p1a). Layout = os/milton/transient.h transient_hdr_t, byte for byte.
; Linked FIRST by os/milton/transient.ld at TRANSIENT_BASE, against the
; running kernel's symbols (ld --just-symbols), so every dd below is the
; address in THAT kernel build. The kernel compares the import addresses with
; its own before it ever jumps here (Rule 2). ASCII only (Rule 12).
bits 32
section .transient_hdr progbits alloc noexec nowrite align=4

extern command_repl
extern command_exec_secondary
extern _tr_load_end
extern _tr_bss_end
; GENERATED by the Makefile's TRANSIENT_IMPORTS_LD rule (gcc-nm -u of the
; transient's C objects, intersected with the kernel's defined symbols): one
; `extern` per kernel import + `%define TRANSIENT_N_IMPORTS <n>`. The kernel
; checks EVERY entry against its own generated table (initech-13ig).
%include "transient_imports_ext.inc"
; MUTANT (Rule 6; test-flair-execguard-mutant IMPORT_SKEW only): the LAST
; import address is offset by this, so the kernel must refuse the transient
; on an import the old hand-kept five-entry check never looked at.
%ifndef TRANSIENT_LAST_IMPORT_SKEW
%define TRANSIENT_LAST_IMPORT_SKEW 0
%endif

global transient_hdr
transient_hdr:
    db 'COMMAND3'                    ; TRANSIENT_MAGIC
    dd command_repl                  ; entry
    dd command_exec_secondary        ; exec_secondary (initech-13ig)
    dd _tr_load_end                  ; load_end
    dd _tr_bss_end                   ; bss_end
    dd TRANSIENT_N_IMPORTS           ; n_imports (generated)
%include "transient_imports_dd.inc"  ; dd <import> ... (generated; last + skew)

section .note.GNU-stack noalloc noexec nowrite progbits
