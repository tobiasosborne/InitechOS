/*
 * tools/calcda_pasdata.c -- emit CALCDATA.PAS, the Calculator's locked layout
 * and glyph strike as Turbo Initech Pascal (factory C; bead initech-tdnl.23
 * R5.3).
 *
 * The Pascal Calculator (os/tps/CALCDA.PAS) paints the SAME face as the C
 * one (os/apps/calcda/calc_view.c): the window and readout geometry and the
 * 18 key rects of spec/calcda/calcda_layout.h and the 31 Geneva 9 glyphs of
 * spec/assets/calcda_geneva9.h. Those are locked spec-data (Rule 8); typing
 * them into Pascal by hand would be a second copy. This tool #includes the
 * two headers and PRINTS them: the geometry as Pascal constants, the two
 * tables as hex strings (two hex digits a byte, at most 200 characters a
 * literal) behind one CalcTableData(Part, D) routine that CALCDA.PAS
 * decodes at start-up -- a few string literals instead of five hundred
 * array assignments (the 64 KiB tenant file cap, spec Sec 8).
 *
 *   key record (8 bytes):    cmd l t w h label ldx ldy
 *   glyph record (12 bytes): ch adv nrows rows[0..8]
 *
 * The output is generated at build time (build/pascal/calcda/CALCDATA.PAS)
 * and planted beside CALCDA.PAS wherever Turbo Initech compiles it; it is
 * never edited and never checked in. Every byte is checked to fit 0..255
 * (the cmd numbers are calc_cmd_t, 0..16).
 *
 * Usage: calcda_pasdata > CALCDATA.PAS. Deterministic (Rule 11), ASCII
 * (Rule 12).
 */
#include <stdio.h>
#include <stdlib.h>
#include "calcda/calcda_layout.h"
#include "calcda_geneva9.h"

static const calc_key_rect_t g_keys[CALC_KEY_COUNT] = CALC_KEY_TABLE;
static const calc_glyph_t    g_g9[CALC_G9_COUNT] = CALC_G9_TABLE;

#define KEYS_PER_PART   12
#define GLYPHS_PER_PART 8

static void byte(int v)
{
    if (v < 0 || v > 255) { fprintf(stderr, "calcda_pasdata: byte %d out of range\n", v); exit(1); }
    printf("%02X", v);
}

int main(void)
{
    int i, r, part, key_parts, glyph_parts;

    key_parts = (CALC_KEY_COUNT + KEYS_PER_PART - 1) / KEYS_PER_PART;
    glyph_parts = (CALC_G9_COUNT + GLYPHS_PER_PART - 1) / GLYPHS_PER_PART;
    printf("{\n  CALCDATA.PAS -- GENERATED by tools/calcda_pasdata.c from\n"
           "  spec/calcda/calcda_layout.h and spec/assets/calcda_geneva9.h\n"
           "  (bead initech-tdnl.23). Do not edit: the headers are the only copy\n"
           "  (Rule 8). Follows FLAIR.PAS, precedes CALCDA.PAS:\n"
           "      COPY /B FLAIR.PAS+CALCDATA.PAS+CALCDA.PAS TPSIN.PAS\n"
           "  Key record (8 bytes): cmd l t w h label ldx ldy.\n"
           "  Glyph record (12 bytes): ch adv nrows rows[0..8].\n}\n");
    printf("const\n");
    printf("  CalcWinL = %d;\n  CalcWinT = %d;\n  CalcWinW = %d;\n  CalcWinH = %d;\n",
           CALC_WIN_L, CALC_WIN_T, CALC_WIN_W, CALC_WIN_H);
    printf("  CalcContentW = %d;\n  CalcContentH = %d;\n", CALC_CONTENT_W, CALC_CONTENT_H);
    printf("  CalcDispL = %d;\n  CalcDispT = %d;\n  CalcDispR = %d;\n  CalcDispB = %d;\n",
           CALC_DISP_L, CALC_DISP_T, CALC_DISP_R, CALC_DISP_B);
    printf("  CalcDispTextRight = %d;\n  CalcDispTextTop = %d;\n",
           CALC_DISP_TEXT_RIGHT, CALC_DISP_TEXT_TOP);
    printf("  CalcKeyShadow = %d;\n  CalcKeyCount = %d;\n", CALC_KEY_SHADOW, CALC_KEY_COUNT);
    printf("  CalcGlyphCount = %d;\n  CalcGlyphRowMax = %d;\n", CALC_G9_COUNT,
           (int)(sizeof g_g9[0].rows / sizeof g_g9[0].rows[0]));
    printf("  CalcKeyParts = %d;\n  CalcGlyphParts = %d;\n\n", key_parts, glyph_parts);

    printf("procedure CalcTableData(Part: integer; var D: string);\nbegin\n  D := '';\n");
    for (part = 0; part < key_parts; part++) {
        printf("  if Part = %d then\n    D := '", part + 1);
        for (i = part * KEYS_PER_PART; i < CALC_KEY_COUNT && i < (part + 1) * KEYS_PER_PART; i++) {
            const calc_key_rect_t *k = &g_keys[i];
            byte(k->cmd); byte(k->l); byte(k->t); byte(k->w); byte(k->h);
            byte((unsigned char)k->label); byte(k->ldx); byte(k->ldy);
        }
        printf("';\n");
    }
    for (part = 0; part < glyph_parts; part++) {
        printf("  if Part = %d then\n    D := '", key_parts + part + 1);
        for (i = part * GLYPHS_PER_PART; i < CALC_G9_COUNT && i < (part + 1) * GLYPHS_PER_PART; i++) {
            const calc_glyph_t *g = &g_g9[i];
            byte((unsigned char)g->ch); byte(g->adv); byte(g->nrows);
            for (r = 0; r < (int)(sizeof g->rows / sizeof g->rows[0]); r++) byte(g->rows[r]);
        }
        printf("';\n");
    }
    printf("end;\n");
    return 0;
}
