/*
 * tools/geneva12_art2h.c -- transcribe the hand-authored Geneva 12 strike
 * (spec/assets/geneva12.art) into the C header the artifact compiles
 * (spec/assets/geneva12.h). Bead initech-uelk; the tools/font_art2h.c pattern
 * (Chicago 12, bead initech-tdnl.33), kept a separate tool so the Chicago
 * transcription stays byte-for-byte untouched.
 *
 * VALIDATION (fail loud, Rule 2 -- a malformed strike never reaches a header):
 *   - glyph blocks are codes FIRST..LAST in order, then exactly one "missing";
 *   - every glyph has exactly CELL_H rows, each exactly `aw` chars of '#'/'.';
 *   - row CELL_H-1 (the leading row) is blank;
 *   - an inked printable glyph's leftmost ink column == lb (the art agrees
 *     with the real NFNT 12112 left bearing written on its glyph line); the
 *     missing box may start right of lb (its NFNT image has a blank column);
 *   - the ink image (rightmost - lb + 1) fits in 16 bits;
 *   - 1 <= aw <= 16, 0 <= lb <= aw.
 *
 * OUTPUT: per glyph, the rows shifted left by lb (image column 0 = pen + lb),
 * MSB = image column 0, as uint16; plus aw[] and lb[].
 *
 * FACTORY CODE (hosted C, Law 3). Deterministic output: no timestamps, no host
 * paths (Rule 11). ASCII-clean (Rule 12).
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define FIRST  0x20
#define LAST   0x7E
#define COUNT  (LAST - FIRST + 1)
#define CELL_H 16
#define NGLYPH (COUNT + 1)         /* printable + missing */

static unsigned g_rows[NGLYPH][CELL_H];
static int g_aw[NGLYPH], g_lb[NGLYPH];
static char g_art[NGLYPH][CELL_H][20];
static int g_line;

static void die(const char *msg)
{
    fprintf(stderr, "geneva12_art2h: line %d: %s\n", g_line, msg);
    exit(1);
}

static char *next_line(FILE *f, char *buf, size_t n)
{
    while (fgets(buf, (int)n, f)) {
        size_t l = strlen(buf);
        g_line++;
        while (l && (buf[l - 1] == '\n' || buf[l - 1] == '\r')) buf[--l] = 0;
        if (buf[0] == ';' || l == 0) continue;
        return buf;
    }
    return NULL;
}

int main(int argc, char **argv)
{
    char buf[256];
    FILE *f;
    if (argc != 2) {
        fprintf(stderr, "usage: geneva12_art2h <strike.art>\n");
        return 2;
    }
    f = fopen(argv[1], "r");
    if (!f) { perror(argv[1]); return 2; }

    for (int gi = 0; gi < NGLYPH; gi++) {
        char name[32];
        int lb, aw, lo = 99, hi = -1;
        if (!next_line(f, buf, sizeof buf)) die("unexpected EOF (missing glyph block)");
        if (sscanf(buf, "glyph %31s lb %d aw %d", name, &lb, &aw) != 3)
            die("expected 'glyph <code> lb <n> aw <n>'");
        if (gi < COUNT) {
            char want[8];
            snprintf(want, sizeof want, "0x%02X", FIRST + gi);
            if (strcmp(name, want) != 0) die("glyph blocks out of order");
        } else if (strcmp(name, "missing") != 0) {
            die("block after 0x7E must be 'missing'");
        }
        if (aw < 1 || aw > 16 || lb < 0 || lb > aw) die("lb/aw out of range");
        for (int r = 0; r < CELL_H; r++) {
            if (!next_line(f, buf, sizeof buf)) die("unexpected EOF inside a glyph");
            if ((int)strlen(buf) != aw) die("row width != aw");
            for (int c = 0; c < aw; c++) {
                if (buf[c] == '#') {
                    if (r == CELL_H - 1) die("ink in the leading row");
                    if (c < lo) lo = c;
                    if (c > hi) hi = c;
                } else if (buf[c] != '.') {
                    die("row chars must be '#' or '.'");
                }
            }
            memcpy(g_art[gi][r], buf, (size_t)aw + 1);
        }
        if (hi >= 0) {
            if (gi < COUNT ? lo != lb : lo < lb)
                die("leftmost ink column != lb (art disagrees with the NFNT bearing)");
            if (hi - lb + 1 > 16) die("ink image wider than 16 columns");
        }
        for (int r = 0; r < CELL_H; r++) {
            unsigned bits = 0;
            for (int c = lb; c < aw; c++)
                if (g_art[gi][r][c] == '#') bits |= 0x8000u >> (c - lb);
            g_rows[gi][r] = bits;
        }
        g_aw[gi] = aw;
        g_lb[gi] = lb;
    }
    if (next_line(f, buf, sizeof buf)) die("trailing data after the missing glyph");
    fclose(f);

    printf("/*\n"
           " * spec/assets/geneva12.h -- GENERATED by tools/geneva12_art2h.c from\n"
           " * spec/assets/geneva12.art. DO NOT EDIT: edit the .art and run\n"
           " * `make gen-geneva12` (test-geneva12-art proves the two are in sync).\n"
           " *\n"
           " * InitechOS \"Geneva 12\" application-font strike (bead initech-uelk):\n"
           " * the face Mac OS 8.1 SimpleText draws its document in. METRICS\n"
           " * (geneva12_aw / geneva12_lb, ascent / descent / leading) are the REAL\n"
           " * Mac OS 8.1 Geneva 12 owTable / FontRec values (NFNT 12112, FOND 3;\n"
           " * see the provenance block in geneva12.art). GLYPH ART is HAND-AUTHORED;\n"
           " * never transcribed from the real strike bitmap.\n"
           " *\n"
           " * Rows: geneva12_rows[g][r], MSB = the glyph IMAGE's first column, which\n"
           " * the renderer places at pen + lb; the opaque cell is aw columns wide.\n"
           " * Index g = c - GENEVA12_FIRST for GENEVA12_FIRST <= c <= GENEVA12_LAST;\n"
           " * otherwise GENEVA12_MISSING.\n"
           " * Linkage: spec/assets/font_linkage.h (one copy per kernel image).\n"
           " */\n"
           "#ifndef INITECH_GENEVA12_H\n"
           "#define INITECH_GENEVA12_H\n\n"
           "#include <stdint.h>\n"
           "#include \"font_linkage.h\"\n\n"
           "#define GENEVA12_FIRST   0x%02X\n"
           "#define GENEVA12_LAST    0x%02X\n"
           "#define GENEVA12_COUNT   (GENEVA12_LAST - GENEVA12_FIRST + 1)\n"
           "#define GENEVA12_MISSING GENEVA12_COUNT\n"
           "#define GENEVA12_GLYPHS  (GENEVA12_COUNT + 1)\n"
           "#define GENEVA12_CELL_H  %d\n"
           "/* NFNT 12112 FontRec: ascent 12, descent 3, leading 1 (the 16-px line\n"
           " * of simpletext-stdfile.md Sec 1.2: 12 + 3 + 1). */\n"
           "#define GENEVA12_ASCENT  12\n"
           "#define GENEVA12_DESCENT 3\n"
           "#define GENEVA12_LEADING 1\n\n",
           FIRST, LAST, CELL_H);

    printf("#if FONT_TABLE_EMIT\n");
    printf("FONT_TABLE unsigned char geneva12_aw[GENEVA12_GLYPHS] = {");
    for (int gi = 0; gi < NGLYPH; gi++)
        printf("%s%d", gi == 0 ? "\n    " : (gi % 16) ? ", " : ",\n    ", g_aw[gi]);
    printf("\n};\n");
    printf("FONT_TABLE unsigned char geneva12_lb[GENEVA12_GLYPHS] = {");
    for (int gi = 0; gi < NGLYPH; gi++)
        printf("%s%d", gi == 0 ? "\n    " : (gi % 16) ? ", " : ",\n    ", g_lb[gi]);
    printf("\n};\n");
    printf("FONT_TABLE uint16_t geneva12_rows[GENEVA12_GLYPHS][GENEVA12_CELL_H] = {\n");
    for (int gi = 0; gi < NGLYPH; gi++) {
        if (gi < COUNT) {
            int c = FIRST + gi;
            printf("/* 0x%02X '%s%c' lb %d aw %d */ {", c,
                   (c == '\\' || c == '\'') ? "\\" : "", (char)c, g_lb[gi], g_aw[gi]);
        } else {
            printf("/* missing lb %d aw %d */ {", g_lb[gi], g_aw[gi]);
        }
        for (int r = 0; r < CELL_H; r++)
            printf("%s0x%04X", r ? "," : "", g_rows[gi][r]);
        printf("},\n");
    }
    printf("};\n#else\n"
           "FONT_TABLE unsigned char geneva12_aw[GENEVA12_GLYPHS];\n"
           "FONT_TABLE unsigned char geneva12_lb[GENEVA12_GLYPHS];\n"
           "FONT_TABLE uint16_t geneva12_rows[GENEVA12_GLYPHS][GENEVA12_CELL_H];\n"
           "#endif\n\n");
    printf("/* Glyph index for byte c: its own slot or the missing-glyph box. */\n"
           "static inline int geneva12_index(int c)\n"
           "{\n"
           "    if (c < GENEVA12_FIRST || c > GENEVA12_LAST)\n"
           "        return GENEVA12_MISSING;\n"
           "    return c - GENEVA12_FIRST;\n"
           "}\n\n"
           "/* The pen advance of byte c (the owTable aw). */\n"
           "static inline int geneva12_advance(int c)\n"
           "{\n"
           "    return (int)geneva12_aw[geneva12_index(c)];\n"
           "}\n\n"
           "#endif /* INITECH_GENEVA12_H */\n");
    return 0;
}
