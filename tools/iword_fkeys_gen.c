/* Deterministic compiler for the LOCKED, line-record fkeys.json schema.
 * Ref: spec/iword/fkeys.json; WP 5.1 Reference pp. 963-966. Factory C.
 * Reject duplicate/missing/out-of-order records, unknown actions, non-ASCII.
 * No timestamps or host paths emitted. */
#include <stdio.h>
#include <string.h>
static const char *const mods[] = { "plain", "shift", "alt", "ctrl" };
static const char *const acts[] = { "gray", "unmapped", "search_forward", "search_backward", "indent", "bold", "exit", "underline", "save", "retrieve", "reveal", "block", "format", "move", "font" };
int main(int argc, char **argv)
{
    char line[512], names[48][40];
    unsigned actions[48], n = 0;
    FILE *f;
    if (argc != 2 || !(f = fopen(argv[1], "r"))) return 2;
    while (fgets(line, sizeof line, f)) {
        char m[16], name[40], a[32], *p = strstr(line, "{\"modifier\":");
        unsigned key, mi, ai;
        for (unsigned i = 0; line[i]; i++) if ((unsigned char)line[i] > 127) goto bad;
        if (!p) continue;
        /* An empty name has its own production: scanf's scanset needs >=1. */
        if (sscanf(p, "{\"modifier\":\"%15[a-z]\",\"key\":%u,\"name\":\"%39[^\"]\",\"action\":\"%31[a-z_]\"}", m, &key, name, a) != 4) {
            name[0] = 0;
            if (sscanf(p, "{\"modifier\":\"%15[a-z]\",\"key\":%u,\"name\":\"\",\"action\":\"%31[a-z_]\"}", m, &key, a) != 3) goto bad;
        }
        for (mi = 0; mi < 4 && strcmp(m, mods[mi]); mi++);
        for (ai = 0; ai < sizeof acts / sizeof acts[0] && strcmp(a, acts[ai]); ai++);
        if (n >= 48 || mi != n / 12 || key != n % 12 + 1 || ai == sizeof acts / sizeof acts[0]) goto bad;
        if ((!name[0]) != (ai == 1)) goto bad;
        for (unsigned i = 0; name[i]; i++) if (name[i] == '\\' || name[i] < ' ') goto bad;
        strcpy(names[n], name); actions[n++] = ai;
    }
    if (ferror(f) || n != 48) goto bad;
    fclose(f);
    puts("/* Generated by tools/iword_fkeys_gen.c from spec/iword/fkeys.json. */\n#ifndef IWORD_FKEYS_H\n#define IWORD_FKEYS_H");
    puts("enum {");
    for (unsigned a = 0; a < sizeof acts / sizeof acts[0]; a++) printf("    IW_FK_%s = %u,\n", acts[a], a);
    puts("};\ntypedef struct { const char *name; unsigned char action; } iw_fkey_t;\nstatic const iw_fkey_t IW_FKEYS[4][12] = {");
    for (unsigned i = 0; i < 48; i++) {
        if (i % 12 == 0) puts("    {");
        printf("        { \"%s\", IW_FK_%s },\n", names[i], acts[actions[i]]);
        if (i % 12 == 11) puts("    },");
    }
    puts("};\n#endif");
    return ferror(stdout) ? 2 : 0;
bad:
    fclose(f); fputs("iword_fkeys_gen: invalid/incomplete 48-slot table\n", stderr); return 1;
}
