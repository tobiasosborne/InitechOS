/* initech-2gva: factory-only, deterministic C. Ref: color_canon.json entries
 * and indexed_alert_extension/ramp_named_indices; clut.json entries enumerate
 * the device's complete 256-slot domain (ADR-0004 OD-2 / DEC-09 ARB-1).
 * IMPORTANT: the ROM CLUT and the product's indexed surface have DIFFERENT
 * index assignments. Do not load ROM RGB triples into the product DAC. The
 * product canon owns explicit colors; its remaining indices are gray ramps.
 * Generate ALL slots so apps using unnamed gray values cannot escape coverage.
 * Output has no paths/timestamps; malformed locked input fails before output.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static void die(const char *why)
{
    fprintf(stderr, "flair_dac_gen: %s\n", why);
    exit(1);
}

static char *slurp(const char *path)
{
    FILE *f = fopen(path, "rb");
    long n;
    char *p;
    if (!f) die("cannot open locked data");
    if (fseek(f, 0, SEEK_END) || (n = ftell(f)) < 0 || n > 1048576 ||
        fseek(f, 0, SEEK_SET)) die("invalid input size");
    p = malloc((size_t)n + 1);
    if (!p || fread(p, 1, (size_t)n, f) != (size_t)n) die("input read");
    p[n] = 0;
    fclose(f);
    return p;
}

/* Parser for these two locked schemas, like color_canon_extract.c. Restrict
 * keys to the current array element, never a following object's fields. */
static const char *key(const char *p, const char *end, const char *name)
{
    char quoted[64];
    snprintf(quoted, sizeof quoted, "\"%s\"", name);
    p = strstr(p, quoted);
    if (!p || p >= end) die("missing key");
    p = strchr(p + strlen(quoted), ':');
    if (!p || p >= end) die("missing colon");
    return p + 1;
}

static unsigned number(const char *p, const char *end)
{
    char *next;
    unsigned long v = strtoul(p, &next, 10);
    if (next == p || next > end || v > 255) die("invalid palette byte");
    return (unsigned)v;
}

static const char *array(const char *text, const char *name)
{
    const char *p = key(text, text + strlen(text), name);
    while (*p == ' ' || *p == '\n' || *p == '\r' || *p == '\t') ++p;
    if (*p != '[') die("missing array");
    return p + 1;
}

static const char *object(const char *p, const char **end)
{
    while (*p == ' ' || *p == '\n' || *p == '\r' || *p == '\t' || *p == ',') ++p;
    if (*p == ']') return NULL;
    if (*p != '{' || !(*end = strchr(p, '}'))) die("missing array object");
    return p;
}

int main(int argc, char **argv)
{
    unsigned char rgb[256][3], domain[256] = {0}, explicit[256] = {0};
    unsigned count = 0, colors = 0;
    const char *p, *end;
    char *clut, *canon;
    if (argc != 3) die("usage: flair_dac_gen clut.json color_canon.json");
    clut = slurp(argv[1]); canon = slurp(argv[2]);
    p = array(clut, "entries");
    while ((p = object(p, &end)) != NULL) {
        unsigned i = number(key(p, end, "index"), end);
        if (domain[i]++) die("duplicate device index");
        /* Validate the RGB schema too, but product colors come from canon. */
        (void)number(key(p, end, "r"), end);
        (void)number(key(p, end, "g"), end);
        (void)number(key(p, end, "b"), end);
        rgb[i][0] = rgb[i][1] = rgb[i][2] = (unsigned char)i;
        ++count; p = end + 1;
    }
    if (count != 256) die("incomplete device index domain");
    p = array(canon, "entries");
    while ((p = object(p, &end)) != NULL) {
        unsigned i = number(key(p, end, "idx"), end);
        const char *bytes = key(p, end, "rgb_bytes");
        if (explicit[i]++) die("duplicate product index");
        bytes = strchr(bytes, '[');
        if (!bytes || bytes >= end) die("missing RGB bytes");
        for (unsigned c = 0; c < 3; ++c) {
            rgb[i][c] = (unsigned char)number(bytes + 1, end);
            bytes = strchr(bytes + 1, c == 2 ? ']' : ',');
            if (!bytes || bytes >= end) die("incomplete RGB bytes");
        }
        ++colors; p = end + 1;
    }
    if (!colors) die("empty product canon");
    p = array(canon, "ramp_named_indices");
    while ((p = object(p, &end)) != NULL) {
        unsigned i = number(key(p, end, "idx"), end);
        if (explicit[i]) die("named ramp collides with explicit color");
        p = end + 1;
    }
    puts("/* GENERATED by tools/flair_dac_gen.c; DO NOT EDIT.\n"
         " * clut.json index domain + color_canon.json explicit colors / gray ramp.\n"
         " * Equality is test-flair-dac; color VALUES are test-color-canon/test-clut. */\n"
         "#ifndef INITECH_FLAIR_DAC_H\n#define INITECH_FLAIR_DAC_H\n"
         "static const unsigned char flair_dac[256][3] = {");
    for (unsigned i = 0; i < 256; ++i) {
#ifdef DAC_GEN_MUT_OMIT
        if (i == DAC_GEN_MUT_OMIT) rgb[i][0] = rgb[i][1] = rgb[i][2] = 0;
#endif
        printf("    {%3u, %3u, %3u}, /* %u */\n", rgb[i][0], rgb[i][1], rgb[i][2], i);
    }
    puts("};\n_Static_assert(sizeof(flair_dac) == 768, \"256 RGB DAC entries\");\n#endif");
    free(clut); free(canon);
    return 0;
}
