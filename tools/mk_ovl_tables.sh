#!/bin/sh
# mk_ovl_tables.sh -- GENERATE the kernel-overlay tables (ADR-0014 DEC-14-1,
# DEC-14-2, DEC-14-6.1; epic initech-x8gsi lane 1). Never hand-kept (the
# initech-13ig lesson, os/milton/transient.h): both sides of every table come
# from the objects.
#
#   imports = symbols the overlay section objects leave undefined that a
#             resident kernel object defines (overlay -> resident; DEC-14-6.3)
#   exports = global text symbols the section objects define that a resident
#             kernel object references (resident -> overlay; reached ONLY
#             through the generated stubs below, DEC-14-6.1/.2)
#
# usage: mk_ovl_tables.sh <out-dir> <nasm> <kdef-file> <kund-file> <obj>...
#   kdef-file: LC_ALL=C sorted names defined by the resident kernel objects
#   kund-file: LC_ALL=C sorted names the resident kernel objects reference
# Writes into <out-dir>:
#   ovl_imports.txt ovl_exports.txt            the two generated name lists
#   ovl_imports_ext.inc ovl_imports_dd.inc ovl_exports_dd.inc
#                                               (%included by overlay_hdr.asm)
#   ovl_kernel.asm -> ovl_kernel.o             the resident side: stubs, the
#                                               want table, the export count and
#                                               the post-link expect slot
#   ovl_undefined.rsp                          -Wl,--undefined= keep flags
# Deterministic: LC_ALL=C everywhere (DEC-14-9(f); research gap G-4).
set -eu
LC_ALL=C
export LC_ALL
out=$1; nasm=$2; kdef=$3; kund=$4; shift 4
[ "$#" -gt 0 ] || { echo '!!! mk_ovl_tables: no overlay section objects' >&2; exit 1; }

# Overlay section objects are native (non-LTO) ELF: plain nm.
for o in "$@"; do nm --defined-only "$o" | awk '$2 ~ /^[A-Z]$/{print $3}'; done | sort -u > "$out/ovl_gdef.txt"
# A name one section object leaves undefined and another defines is resolved
# INSIDE the overlay link, never imported from the kernel.
for o in "$@"; do nm -u "$o" | awk '{print $NF}'; done | sort -u | comm -23 - "$out/ovl_gdef.txt" > "$out/ovl_und.txt"
for o in "$@"; do nm --defined-only "$o" | awk '$2=="T"{print $3}'; done | sort -u > "$out/ovl_def.txt"
comm -12 "$out/ovl_und.txt" "$kdef" > "$out/ovl_imports.txt"
comm -12 "$out/ovl_def.txt" "$kund" > "$out/ovl_exports.txt"
# Every name the sections leave undefined must be a resident kernel symbol:
# anything else would only surface as an overlay link error later.
missing=$(comm -23 "$out/ovl_und.txt" "$kdef")
[ -z "$missing" ] || { printf '!!! mk_ovl_tables: overlay needs symbols no resident object defines: %s\n' "$missing" >&2; exit 1; }
ni=$(wc -l < "$out/ovl_imports.txt"); ne=$(wc -l < "$out/ovl_exports.txt")
[ "$ni" -gt 0 ] || { echo '!!! mk_ovl_tables: zero imports -- the derivation is broken' >&2; exit 1; }
[ "$ne" -gt 0 ] || { echo '!!! mk_ovl_tables: zero exports -- nothing resident calls the overlay' >&2; exit 1; }

# DEC-14-6.5: overlaid code never installs an IRQ hook or touches the IDT.
bad=$(grep -E '^(pit_set_tick_hook|kbd_set_scancode_hook|mouse_set_event_hook|panic_set_fault_hook|idt_.*)$' "$out/ovl_imports.txt" || true)
[ -z "$bad" ] || { printf '!!! mk_ovl_tables: DEC-14-6.5 overlay imports an IRQ/IDT hook setter: %s\n' "$bad" >&2; exit 1; }

{ sed 's/^/extern /' "$out/ovl_imports.txt"; sed 's/^/extern /' "$out/ovl_exports.txt"
  printf '%%define OVL_N_IMPORTS %s\n%%define OVL_N_EXPORTS %s\n' "$ni" "$ne"; } > "$out/ovl_imports_ext.inc"
{ sed '$d' "$out/ovl_imports.txt" | sed 's/^/    dd /'
  printf '    dd %s + OVL_LAST_IMPORT_SKEW\n' "$(tail -n 1 "$out/ovl_imports.txt")"; } > "$out/ovl_imports_dd.inc"
sed 's/^/    dd /' "$out/ovl_exports.txt" > "$out/ovl_exports_dd.inc"
sed 's/^/-Wl,--undefined=/' "$out/ovl_imports.txt" > "$out/ovl_undefined.rsp"

# The resident side. spec/overlay_format.h: exports sit at OVERLAY_BASE +
# 32 (fixed) + 20 * n_sections + 4 * n_imports; lane 1 has one section.
# Each stub: call ovl_check (VALID, or load with every register saved), then
# an indirect jump through the overlay's own export slot, so the callee sees
# the caller's return address and stack arguments untouched (kernel ABI
# -mregparm=3 -mrtd: EAX/EDX/ECX are preserved by pushad/popad).
exp_base=$(( 0x5C0000 + 32 + 20 * 1 + 4 * ni ))
{
  printf '; GENERATED by tools/mk_ovl_tables.sh (ADR-0014). Do not edit.\n'
  printf 'bits 32\n'
  sed 's/^/extern /' "$out/ovl_imports.txt"
  printf 'extern ovl_need\nextern ovl_state\n'
  printf 'section .text.ovl_stubs progbits alloc exec nowrite align=1\n'
  i=0
  while read -r e; do
    slot=$i
    # MUTANT (Rule 6; test-ovl-behaviour-mutant only): every stub resolved
    # to the WRONG export (the slots rotated by one, so none stays put).
    # Never in a real build.
    [ "${OVL_MUT_SWAP_STUBS:-0}" = 1 ] && slot=$(( (i + 1) % ne ))
    printf 'global %s\n%s:\n    call ovl_check\n    jmp [dword 0x%08X]\n' "$e" "$e" $(( exp_base + 4 * slot ))
    i=$(( i + 1 ))
  done < "$out/ovl_exports.txt"
  printf 'ovl_check:\n    cmp byte [ovl_state], 1\n    jne .load\n    ret\n'
  printf '.load:\n    pushad\n    call ovl_need\n    popad\n    ret\n'
  printf 'section .rodata.ovl_kernel progbits alloc noexec nowrite align=4\n'
  printf 'global ovl_import_want\nglobal ovl_import_count\nglobal ovl_export_count\nglobal ovl_kernel_expect\n'
  printf 'ovl_import_want:\n'
  sed 's/^/    dd /' "$out/ovl_imports.txt"
  printf 'ovl_import_count:\n    dd %s\novl_export_count:\n    dd %s\n' "$ni" "$ne"
  printf '; {crc32, identity}: the placeholder "OVLCRC??" (spec/overlay_format.h),\n'
  printf '; replaced after the overlay link by tools/flairovl.c pack.\n'
  printf 'ovl_kernel_expect:\n    dd 0x434C564F, 0x3F3F4352\n'
  printf 'section .note.GNU-stack noalloc noexec nowrite progbits\n'
} > "$out/ovl_kernel.asm"
"$nasm" -f elf32 "$out/ovl_kernel.asm" -o "$out/ovl_kernel.o"
printf '>>> overlay tables: %s imports, %s exports (%s); stubs + want table generated\n' "$ni" "$ne" "$(tr '\n' ' ' < "$out/ovl_exports.txt")"
