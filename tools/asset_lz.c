/* tools/asset_lz.c -- build-time STORAGE packing of locked strike data for
 * the kernel (kernel size round 5, WL-0168). FACTORY C, host only.
 *
 * Ref: PRD Sec 5/6.4 (the kernel window is a gated resource); the round-4
 *      chicago_pack precedent (tools/chicago_pack.c, WL-0152): the LOCKED
 *      headers stay the only source of every byte; this tool emits a packed
 *      copy and harness/proptest/test_asset_lz.c proves decode == locked.
 *      Locked sources (UNCHANGED, Rule 8): spec/assets/desk_icons.h,
 *      finder_icons.h, alert_icons.h, finder_small_icons.h, boot_logo.h.
 *
 * The packed form is LZSS (os/flair/asset_lz.h is the decoder and the format
 * contract): a flag byte announces eight items, LSB first; a 1 bit is one
 * literal byte, a 0 bit a two-byte little-endian match word w with distance
 * (w >> 4) + 1 (1..4096) and length (w & 15) + 3 (3..18). The parse is an
 * exact shortest-path (literal 9 bits, match 17 bits), ties broken toward the
 * literal and then the shortest distance -- deterministic, no timestamps
 * (Rule 11). Output: the committed os/flair/asset_lz_data.h; the drift tooth
 * (test-asset-lz) regenerates it and compares byte for byte.
 */
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "desk_icons.h"
#include "finder_icons.h"
#include "alert_icons.h"
#include "finder_small_icons.h"
#include "boot_logo.h"

/* The kernel decodes into a FLAIRDeskIcon of the i386 layout; the host
 * layout must be the same bytes (both little-endian, uint32_t 4-aligned). */
_Static_assert(sizeof(FLAIRDeskIcon) == 528u, "FLAIRDeskIcon is 16 + 512 bytes");
_Static_assert(offsetof(FLAIRDeskIcon, px) == 16u, "px follows the tone table");

#define LZ_MAX_IN   4096u
#define LZ_MIN_LEN  3u
#define LZ_MAX_LEN  18u
#define LZ_MAX_DIST 4096u

static unsigned lz_pack(const uint8_t *in, unsigned n, uint8_t *out)
{
    static unsigned cost[LZ_MAX_IN + 1], step[LZ_MAX_IN + 1], dist[LZ_MAX_IN + 1];
    unsigned i, o = 0, flag_at = 0, items = 0;

    cost[n] = 0;
    for (i = n; i-- > 0;) {
        cost[i] = cost[i + 1] + 9u; step[i] = 1u; dist[i] = 0u;
        for (unsigned d = 1; d <= LZ_MAX_DIST && d <= i; d++) {
            unsigned l = 0;
            while (l < LZ_MAX_LEN && i + l < n && in[i + l] == in[i + l - d]) l++;
            for (unsigned k = LZ_MIN_LEN; k <= l; k++) {
                if (cost[i + k] + 17u < cost[i]) {
                    cost[i] = cost[i + k] + 17u; step[i] = k; dist[i] = d;
                }
            }
        }
    }
    for (i = 0; i < n; i += step[i], items++) {
        if (items % 8u == 0u) { flag_at = o; out[o++] = 0u; }
        if (step[i] == 1u) {
            out[flag_at] |= (uint8_t)(1u << (items % 8u));
            out[o++] = in[i];
        } else {
            unsigned w = ((dist[i] - 1u) << 4) | (step[i] - LZ_MIN_LEN);
            out[o++] = (uint8_t)(w & 0xFFu);
            out[o++] = (uint8_t)(w >> 8);
        }
    }
    return o;
}

static void emit(const char *guard, const char *name, const char *raw_macro,
                 const void *const *parts, const unsigned *sizes, unsigned nparts)
{
    static uint8_t in[LZ_MAX_IN], out[LZ_MAX_IN * 2u];
    unsigned n = 0, m;

    for (unsigned p = 0; p < nparts; p++) {
        memcpy(in + n, parts[p], sizes[p]);
        n += sizes[p];
    }
    m = lz_pack(in, n, out);
    printf("\n#ifdef %s\n#define %s %uu\n", guard, raw_macro, n);
    printf("static const uint8_t %s[%u] = {", name, m);
    for (unsigned i = 0; i < m; i++)
        printf("%s%s%u", i ? "," : "", (i % 24u) ? "" : "\n    ", out[i]);
    printf("\n};\n#endif /* %s */\n", guard);
    fprintf(stderr, "asset_lz: %s %u -> %u B\n", name, n, m);
}

int main(void)
{
    const void *desk[6] = { &FLAIR_DESK_ICON_VOLUME, &FLAIR_DESK_ICON_TRASH,
                            &FLAIR_DESK_ICON_TRASH_FULL, &FLAIR_FINDER_ICON_FOLDER,
                            &FLAIR_FINDER_ICON_DOC, &FLAIR_FINDER_ICON_APP };
    const unsigned desk_n[6] = { 528u, 528u, 528u, 528u, 528u, 528u };
    const void *alert[1] = { &FLAIR_ALERT_ICON_CAUTION };
    const unsigned alert_n[1] = { 528u };
    const void *small[1] = { finder_small_art };
    const unsigned small_n[1] = { (unsigned)sizeof finder_small_art };
    const void *logo[1] = { boot_logo_rle };
    const unsigned logo_n[1] = { (unsigned)sizeof boot_logo_rle };

    puts("/* os/flair/asset_lz_data.h -- GENERATED by tools/asset_lz.c\n"
         " * (make gen-asset-lz). DO NOT EDIT: the locked spec/assets headers are the\n"
         " * source of every byte; test-asset-lz regenerates this file and proves\n"
         " * decode == locked. Packed storage only (os/flair/asset_lz.h); no\n"
         " * timestamps (Rule 11). Each block is compiled only by the TU that names\n"
         " * its guard. */\n"
         "#ifndef INITECH_ASSET_LZ_DATA_H\n#define INITECH_ASSET_LZ_DATA_H\n"
         "#include <stdint.h>");
    puts("\n/* VOLUME, TRASH, TRASH_FULL (desk_icons.h), FOLDER, DOC, APP\n"
         " * (finder_icons.h): six FLAIRDeskIcon records in this order. */");
    emit("ASSET_LZ_DESK", "asset_lz_desk", "ASSET_LZ_DESK_RAW", desk, desk_n, 6u);
    puts("\n/* CAUTION (alert_icons.h): one FLAIRDeskIcon record. */");
    emit("ASSET_LZ_ALERT", "asset_lz_alert", "ASSET_LZ_ALERT_RAW", alert, alert_n, 1u);
    puts("\n/* finder_small_art[3][256] (finder_small_icons.h). */");
    emit("ASSET_LZ_SMALL", "asset_lz_small", "ASSET_LZ_SMALL_RAW", small, small_n, 1u);
    puts("\n/* boot_logo_rle[BOOT_LOGO_RLE_BYTES] (boot_logo.h). */");
    emit("ASSET_LZ_LOGO", "asset_lz_logo", "ASSET_LZ_LOGO_RAW", logo, logo_n, 1u);
    puts("\n#endif /* INITECH_ASSET_LZ_DATA_H */");
    return ferror(stdout) ? 1 : 0;
}
